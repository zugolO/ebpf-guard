# ВХОД КОНТРОЛЯ ЛЕЖИТ ВНЕ $ART. Смок 18.09.2026 показал почему:
# wave6.3-controls.sh чистит $W63_ART при СВОЁМ старте (`rm -rf` в его шапке),
