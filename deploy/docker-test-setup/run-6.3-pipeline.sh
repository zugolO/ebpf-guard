# Цель — настоящий резолвер ноды, а не выдуманный адрес: connect() на
# недостижимый хост тоже создал бы запись, но повторяемость контроля на
# другом стенде тогда зависела бы от его маршрутов.
_r63_bfpos_target=$(awk '$1=="nameserver" && $2 !~ /:/ {print $2; exit}' /etc/resolv.conf 2>/dev/null)
_r63_bfpos_target="${_r63_bfpos_target:-8.8.8.8}"
# Держатель — ОДИН процесс и РОВНО ОДИН exec. Первая версия ждала снятия
# циклом `while …; do sleep 1; done`, то есть экала `sleep` раз в секунду всё
# время, пока держит сокет. `sleep` — ровно одно из шумных родовых имён этого
# узла (anomaly_detection на нём срабатывает в каждом окне), и контроль
# подмешивал бы СЕБЯ в базу профилировщика во время пролога: измеритель,
# обучающий профиль, который потом измеряет. Вместо цикла — `exec sleep`:
# дескриптор соединённого сокета переживает exec (не CLOEXEC), pid остаётся
# тем же (важно и для чтения /proc/<pid>/net/udp, и для kill), процесс ровно
# один, а таймаут страхует от осиротевшего держателя, если пайплайн умрёт
# ([[control-artifacts-must-live-outside-root]] — та же гигиена).
bash -c '
    exec 3<>/dev/udp/'"$_r63_bfpos_target"'/53 || exit 1
    echo "$$" > "$1"
    exec sleep "$2"
' _ "$_r63_bfpos_ready" "$_r63_bfpos_hold_secs" &
_r63_bfpos_holder=$!
_r63_n=0
while [ ! -s "$_r63_bfpos_ready" ] && [ "$_r63_n" -lt 10 ]; do sleep 1; _r63_n=$(( _r63_n + 1 )); done
_r63_bfpos_pid=$(cat "$_r63_bfpos_ready" 2>/dev/null || echo "")
# Свой прибор: соединённый сокет на :53 в /proc того самого процесса.
_r63_bfpos_line=""
if [ -n "$_r63_bfpos_pid" ] && [ -r "/proc/$_r63_bfpos_pid/net/udp" ]; then
    # Предикат ТОТ ЖЕ, что у продукта (connectedPort53Inodes,
    # dns_backfill.go): rem_address — колонка 3, inode — колонка 10, порт
    # 0035, И адрес назначения не нулевой. Более слабый сторож входа
    # объявил бы «вход установлено» на сокете, который бэкфилл законно
    # пропускает, и напечатал бы ложное «слеп».
    _r63_bfpos_line=$(awk 'NR>1 {
            split($3, ra, ":")
            if (ra[2] == "0035" && ra[1] ~ /[1-9a-fA-F]/) { print $3" inode="$10; exit }
        }' "/proc/$_r63_bfpos_pid/net/udp" 2>/dev/null)
fi
if [ -n "$_r63_bfpos_line" ]; then
    _r63_bfpos_pre="установлено"
    echo "  положительный контроль бэкфилла (№340): держу СОЕДИНЁННЫЙ UDP-сокет на ${_r63_bfpos_target}:53 (pid $_r63_bfpos_pid, $_r63_bfpos_line) через рестарт агента — вход контроля подтверждён СВОИМ прибором"
else
    _r63_bfpos_pre="НЕ УСТАНОВЛЕНО"
    echo "  ⚠ положительный контроль бэкфилла (№340): соединённый сокет на ${_r63_bfpos_target}:53 поднять НЕ УДАЛОСЬ (pid '${_r63_bfpos_pid:-нет}') — положительный случай на этом прогоне неизмерим, отрицательная половина 6.3.1.1 не страдает"
fi
{
    echo "target=$_r63_bfpos_target"
    echo "holder_pid=${_r63_bfpos_pid:-}"
    echo "precondition=$_r63_bfpos_pre"
    echo "proc_line=${_r63_bfpos_line:-}"
} > "$_r63_bfpos"

_r63_pre_restart=$(date -u +%s)
# PST ПРЕЖНЕГО агента — опорная величина барьера готовности ниже. Сравнение с
# ОТМЕТКОЙ ВРЕМЕНИ здесь не работает, и смок 18.09.2026 показал это на здоровом
# агенте: остановка и старт уложились в одну секунду, а
# process_start_time_seconds считается как btime + starttime/HZ, где btime —
# целые секунды из /proc/stat со своей погрешностью. Новый агент получил
# PST=1789688593.97 при отметке 1789688594, строгое «больше» не выполнилось
# НИКОГДА, и барьер убил здоровый прогон на 90-й секунде. Неравенство двух
# ЧТЕНИЙ ОДНОЙ И ТОЙ ЖЕ величины от арифметики часов не зависит вовсе.
_r63_pst_old=$(curl -s --max-time 10 \
    -H "Authorization: Bearer ${EBPF_GUARD_TOKEN:-$(grep '^admin=' /var/lib/ebpf-guard/token 2>/dev/null | cut -d= -f2)}" \
    "${W63_PIPE_API}/metrics" 2>/dev/null \
    | awk '$1=="process_start_time_seconds"{print $2; exit}')
systemctl stop "$SVC"
rm -f /var/lib/ebpf-guard/test-events.db /var/lib/ebpf-guard/test-events.db-wal /var/lib/ebpf-guard/test-events.db-shm
systemctl start "$SVC"
# №240: момент старта пишется ДВАЖДЫ — читаемой строкой и ЭПОХОЙ. journalctl
# кормится эпохой: systemd.time(7) не разбирает ISO-8601 с суффиксом «T…Z»
