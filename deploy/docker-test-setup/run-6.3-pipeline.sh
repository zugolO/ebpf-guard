    echo "  СТОП: profiler.lineage.enabled: false — атрибуция по дереву (6.2.9.F.3) недостижима, доля измерителя не считается"; _r63_in_fail=1
else
    echo "  OK: profiler.lineage не выключен явно — источник родословной есть"
fi

# (4) СОСТАВ СБОРКИ БИНАРЯ СООТВЕТСТВУЕТ КОНФИГУ (волна 6.3.L, №421).
#     `policy.rego.enabled` по умолчанию true, а `make build` собирает БЕЗ
#     тега `rego` (тег даёт только `make build-rego`, и кладёт он бинарь под
#     ДРУГИМ именем). Агент на такой сборке поднимается штатно, пишет ОДИН
#     WARN в журнал и работает со стубом: ни одного решения Rego, ни одного
#     переименования, ни одного rego_action. Прогон 21.09.2026 прошёл целиком
#     на таком бинаре и стоил трёх меток разом — 6.3L.1/6.3L.2/6.3L.3 вынесли
#     «НЕИЗМЕРИМ: Rego не переименовал ни одного алерта», то есть приборный
#     ноль, неотличимый от продуктового без чтения журнала. Спрашивается
#     СОСТАВ У ТОГО САМОГО БИНАРЯ (`version` печатает `build-tags: rego=…`),
#     а не у Makefile и не у читателя журнала.
_r63_rego_cfg=$(awk '
    /^policy:/{p=1; next}
    p && /^[A-Za-z#]/{exit}
    p && /^[[:space:]]{2}rego:[[:space:]]*$/ { r=1; next }
    p && r && /^[[:space:]]{2}[a-z_]+:/ { exit }
    p && r && /enabled:[[:space:]]*(true|false)/ { print ($2 == "true") ? "on" : "off"; exit }' "$_r63_cfg" 2>/dev/null)
_r63_rego_cfg="${_r63_rego_cfg:-on}"   # умолчание продукта — true
if [ -x "$_r63_bin" ]; then
    _r63_bin_tags=$("$_r63_bin" version 2>/dev/null | grep -oE 'rego=(true|false)' | head -1)
    if [ -z "${_r63_bin_tags:-}" ]; then
        echo "  СТОП: $_r63_bin не печатает состав сборки (build-tags) — бинарь старше правки №421,"
        echo "      и спросить его, собран ли он с тегом rego, нечем. Пересобрать текущим HEAD."
        _r63_in_fail=1
    elif [ "$_r63_rego_cfg" = "on" ] && [ "$_r63_bin_tags" = "rego=false" ]; then
        echo "  СТОП: конфиг просит слой Rego (policy.rego.enabled=true), а бинарь собран БЕЗ тега rego."
        echo "      Такой прогон НЕ провалится — он напечатает «Rego не переименовал ничего» по меткам"
        echo "      6.3L.1/6.3L.2/6.3L.3 и 6.3r.2/6.3r.4, и этот ноль будет приборным (№421, 21.09.2026)."
        echo "      Собирать: go build -tags rego -pgo=auto -o $_r63_bin ./cmd/ebpf-guard"
        _r63_in_fail=1
    else
        echo "  OK: состав сборки согласован с конфигом — бинарь $_r63_bin: ${_r63_bin_tags}, policy.rego.enabled=${_r63_rego_cfg}"
    fi
fi

if [ "$_r63_in_fail" -ne 0 ]; then
