# ── ОПОРНЫЙ НАБОР ПОЛОЖИТЕЛЬНЫХ КОНТРОЛЕЙ (item 3 волны 6.3.9.F, находка №370).
#
#    ПРОВЕНАНС ПЕЧАТАЕТСЯ СЛОВОМ, И ОН ЗАВИСИТ ОТ ТОГО, КТО СНЯЛ РЕЕСТРЫ.
#    До item 5 волны 6.3-rid набор снимался ДВУМЯ отдельными прогонами, и этот
#    каталог был НАМЕРЕННО СТАРЫМ — единственным исключением из №228 («ничего
#    из каталогов прошлых прогонов»): весь смысл опорного снимка был в том,
#    что он снят РАНЬШЕ, на другом бинаре. После item 5 обе роли снимает САМ
#    этот прогон (W63_BASELINE_CONTROLS=on, W3_FORCE=1), и подпись «НЕ этого
#    прогона» стала бы ложной ровно в том месте архива, где читатель через
#    сутки выясняет, ЧТО с чем сравнила 6.3.9.5. Строка выбирается по факту, а
#    не по прежнему умолчанию.
_w63_bl="${W63_BASELINE_ART:-/var/lib/w639f3-item3-artifacts}"
if [ -d "$_w63_bl" ]; then
    mkdir -p "$COLLECT/controls/baseline-item3" 2>/dev/null
    cp -r "$_w63_bl/." "$COLLECT/controls/baseline-item3/" 2>/dev/null
    if [ "${_w63_blc:-off}" != "off" ]; then
        echo "  опорный набор item 3 (ОБЕ роли сняты ЭТИМ прогоном, item 5 волны 6.3-rid — класс сравнения 6.3.9.5 см. выше):"
    else
        echo "  опорный набор item 3 (НЕ этого прогона — W63_BASELINE_CONTROLS=off, реестры унаследованы с диска):"
    fi
    ls -l --time-style=long-iso "$_w63_bl" 2>/dev/null | sed 's/^/    /' || ls -l "$_w63_bl" | sed 's/^/    /'
else
    echo "  опорный набор item 3 НЕ НАЙДЕН в $_w63_bl — 6.3.9.5 сравнивать не с чем (находка №370)"
fi

