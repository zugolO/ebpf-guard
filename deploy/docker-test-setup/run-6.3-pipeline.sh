    _r63_bfpos_pre="установлено"
    echo "  положительный контроль бэкфилла (№340): держу СОЕДИНЁННЫЙ UDP-сокет на ${_r63_bfpos_target}:53 (pid $_r63_bfpos_pid, $_r63_bfpos_line) через рестарт агента — вход контроля подтверждён СВОИМ прибором"
else
    _r63_bfpos_pre="НЕ УСТАНОВЛЕНО"
    echo "  ⚠ положительный контроль бэкфилла (№340): соединённый сокет на ${_r63_bfpos_target}:53 поднять НЕ УДАЛОСЬ (pid '${_r63_bfpos_pid:-нет}') — положительный случай на этом прогоне неизмерим, отрицательная половина 6.3.1.1 не страдает"
fi
{
    echo "target=$_r63_bfpos_target"
    echo "holder_pid=${_r63_bfpos_pid:-}"
    echo "precondition=$_r63_bfpos_pre"
    echo "proc_line=${_r63_bfpos_line:-}"
} > "$_r63_bfpos"

