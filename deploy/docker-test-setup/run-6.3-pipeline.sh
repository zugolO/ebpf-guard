#    постановки волны 6.3.1 («ноль — это перемещение находки, а не её
#    закрытие») остаётся открытым.
#
#    Ждать прогона, на который повезёт, бессмысленно — разбор прогона #4
#    объяснил ноль механизмом: `coredns` этой ноды поднимает форвардящий
#    сокет НА ЗАПРОС (доказано алертом `exfil_dns_txt_long_label` с
#    comm=coredns в журнале — значит сокет создан ПОСЛЕ старта агента и
#    поймался trace_connect), долгоживущих соединённых :53 на ebaka2 нет
#    вовсе. Значит положительный случай надо СОЗДАТЬ, а не выждать.
#
#    Стоимость контроля — ноль DNS-событий и ноль алертов: `exec 3<>/dev/udp`
#    делает socket()+connect(), но НИ ОДНОГО байта не отправляет. В
#    /proc/<pid>/net/udp запись появляется, трафика нет.
#
#    Сторож входа — свой, независимый от агента: контроль сам читает
#    /proc/<holder>/net/udp и требует увидеть там порт назначения 0035.
#    Без этого «candidates=0» снова был бы неотличим от «держать сокет не
#    удалось» ([[positive-control-needs-result-sentinel]]).
# ВХОД КОНТРОЛЯ ЛЕЖИТ ВНЕ $ART. Смок 18.09.2026 показал почему:
# wave6.3-controls.sh чистит $W63_ART при СВОЁМ старте (`rm -rf` в его шапке),
# а пайплайн пишет сюда за полчаса до него — файл до читателя не доживал, и
# 6.3.1.1 печатал класс «не_снят» при фактическом «взят» (candidates=1,
# backfilled=1). То есть положительный случай был снят и потерян по дороге:
# приборный ноль ровно того класса, ради которого контроль и заводился.
