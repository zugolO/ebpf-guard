_w639_pstat() { # $1 = снимок /debug/state, $2 = ключ внутри profiler_stats
    [ -s "$1" ] || { printf ''; return; }
    if command -v jq >/dev/null 2>&1; then
        jq -r --arg k "$2" '.profiler_stats[$k] // empty' "$1" 2>/dev/null
        return
    fi
    # Резерв без jq: ключ берётся ТОЛЬКО внутри блока profiler_stats — те же
    # имена (anomalies_total) встречаются и в соседних разделах снимка.
    awk -v k="$2" '
        /"profiler_stats"[[:space:]]*:/ { inp = 1; next }
        inp && /^  \}/ { inp = 0 }   # mawk на ноде не знает интервалов {2}
        inp {
            re = "\"" k "\"[[:space:]]*:[[:space:]]*"
            if (match($0, re)) {
                s = substr($0, RSTART + RLENGTH)
                if (match(s, /^-?[0-9]+/)) { print substr(s, 1, RLENGTH) + 0; exit }
            }
        }' "$1" 2>/dev/null
}
