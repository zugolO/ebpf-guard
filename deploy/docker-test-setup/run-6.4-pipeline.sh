#     Двигать маркеры можно; выкидывать — нет: без них сторож объявляет
#     себя неизмеримым и роняет преflight.
# ── СНИМКИ /debug/state НА ГРАНИЦАХ ОКНА — ВХОД СРАЗУ ТРЁХ МЕТОК.
#
# Читаются ДО первой вердиктной строки, потому что отвечают на вопрос, от
# которого зависят и 6.3.9.3 (досев работает), и 6.3.9.4 (цена ПОСЛЕ правок),
# и формулировка 6.3.9.1 (цена ДО правок): НЕСЁТ ЛИ РАБОТАЮЩИЙ БИНАРЬ ПРАВКУ
# ДОСЕВА. Признак — наличие ключа seeded_observations_total в снимке; «прогон
# A» и «прогон B» суть ровно это свойство бинаря, а не имя запуска и не флаг
# оператора, который можно передать неверно.
_w639_pstat() { # $1 = снимок /debug/state, $2 = ключ внутри profiler_stats
    [ -s "$1" ] || { printf ''; return; }
    if command -v jq >/dev/null 2>&1; then
        jq -r --arg k "$2" '.profiler_stats[$k] // empty' "$1" 2>/dev/null
        return
    fi
    # Резерв без jq: ключ берётся ТОЛЬКО внутри блока profiler_stats — те же
    # имена (anomalies_total) встречаются и в соседних разделах снимка.
    awk -v k="$2" '
        /"profiler_stats"[[:space:]]*:/ { inp = 1; next }
        inp && /^  \}/ { inp = 0 }   # mawk на ноде не знает интервалов {2}
        inp {
            re = "\"" k "\"[[:space:]]*:[[:space:]]*"
            if (match($0, re)) {
                s = substr($0, RSTART + RLENGTH)
                if (match(s, /^-?[0-9]+/)) { print substr(s, 1, RLENGTH) + 0; exit }
            }
        }' "$1" 2>/dev/null
}
