# Форк run-6.3-pipeline.sh, СДЕЛАННЫЙ ПО ТОЙ ЖЕ КОНВЕНЦИИ, по которой сам
# run-6.3-pipeline.sh форкался от run-6.2.6-pipeline.sh: унаследованная общая
# машинерия измерения (границы окна, тихое окно объёма, приборность оси пода,
# самоскан, ресурсы, drain-реконсиляция, атрибуция по дереву, страж полноты,
# статическая сверка, фикстурный сторож эмиттеров) остаётся БЕЗ переименования
# — метки 6.2.6.*/6.3.9.*/6.3L.*/6.3L1.* держат СВОИ номера и живут в тексте
# этого файла нетронутыми (память [[criteria-index-pins-replay-labels]]).
#
# ЧТО УЖЕ ЗАВЕДЕНО В КОДЕ/ПРАВИЛАХ ДО ЭТОГО ФОРКА (items 1…7 постановки 6.4,
# см. plan.md): манифест 23 rule_id двумя секциями семейств (plaintext/ja3,
# item 1); починка №379 — DynamicSymbols() с фолбэком, счётчик
# ebpf_guard_tls_attach_failures_total{reason} (item 2); №380 — открытие
