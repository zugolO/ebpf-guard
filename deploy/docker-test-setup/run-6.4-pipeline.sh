# владельца по JA3 (item 4, закрыта 23.09.2026 находкой №433, исход (б) —
# см. 6.4.5 ниже); контроли items 5/6 (положительный plaintext-контроль
# долгоживущим процессом и контейнерный случай) — по постановке они ещё
# 📋, эмиттеры 6.4.3/6.4.4 читают их результат через сторожевые файлы, а не
# гадают; офлайн-прогон 23 правил через internal/ruletest (item 7).
#
# ОГОВОРКА ЭТОГО ФОРКА (офлайн-заход, без стенда): рабочее дерево, из
# которого сделан этот форк, НЕ несёт живых правок items 1…7 (ни
# generate-tls-rule-manifest.sh, ни tls-rule-ids.txt, ни DynamicSymbols() в
# internal/collector/tls.go) — они существуют как незакоммиченные правки в
# ДРУГОЙ рабочей копии репозитория, недоступной этому воркетри. Каждая ветка
# ниже, которая читает эти артефакты, УЖЕ проверяет их существование и
# называет класс НЕИЗМЕРИМ/ПРОВАЛЕН с явной причиной при их отсутствии —
# ничего не гадает и не фабрикует. Живой прогон на стенде обязан подтянуть
# items 1…7 ПЕРЕД первым запуском этого пайплайна.
#
# ЧТО ДОБАВЛЕНО ОТНОСИТЕЛЬНО 6.3-ВЕРСИИ (item 8 постановки 6.4, не
# механический форк):
#
#   Шаг 0    — реестр сужений волны 6.3 (11 DNS-правил с изменённым условием,
#              находка №329) СНЯТ: волна 6.4 не меняет условий ни одного
#              правила, items 1…7 правят Go-код коллектора и mount-ns путь,
#              а не YAML условий. Реестр idle-actors.txt (акторы ноды) и
#              сторож осиротевших циклов ожидания — ОБЩАЯ ГИГИЕНА, остаются.
#   Шаг 0в   — вход измерения переписан под 6.4: включённый TLS-коллектор
#              (`collectors.tls.enabled`) ВМЕСТО DNS, флаг
#              `exporter.volume_by_source` (входное условие (в) постановки —
#              без него объём читать нечем, №410), манифест 23 TLS rule_id
#              двумя секциями семейств ВМЕСТО манифеста DNS.
#   W648     — НОВЫЙ блок эмиттеров меток 6.4.0…6.4.8 (item 8 постановки),
#              между маркерами блока W648 (см. ниже по файлу, помечен
#              явно) — см. ниже по файлу.
#              Старый блок W639-EMITTERS (метки 6.3.9.1…6.3.9.8, диагностика
#              DNS-шума) ОСТАВЛЕН ТЕЛОМ БЕЗ ИЗМЕНЕНИЙ — код мёртв для волны
#              6.4 (её собственная таблица меток, wave6.4-completeness-guard.sh,
#              этих меток не требует — постановка 6.4 их не называет), но
#              выкидывать тело не за чем: инвариант архива №228 («ничего не
#              копируется из каталогов прошлых волн») тут ни при чём, а
#              удаление куска, который однажды кому-то понадобится читать
#              вручную, ничего не выигрывает и увеличивает риск правки.
#
# ПАРАМЕТРЫ ПРОГОНА (plan.md §«Параметры прогона» волны 6.4): пролог 1800 с
# — НЕ ради базы дрейфа (TLS-события до профилировщика не доходят,
# EventTLS отсутствует в analyzeBehavior), а ради сравнимости окна с
# архивами 6.2.x/6.3.x; окно 600 с, форсированный тик ноды AccuracySec=1s.
# Прогон A — collectors.tls.enabled: false (цена окна БЕЗ TLS, половина пары
# 6.4.6); прогон B — tls.enabled: true (+tls_fingerprint по исходу развилки
# item 4, см. 6.4.5) — метки 6.4.2…6.4.5 выносят вердикт ЗДЕСЬ. Оба прогона —
# ДВА ОТДЕЛЬНЫХ ЗАПУСКА этого файла с разным config-test.yaml между ними;
# сам пайплайн конфиг НЕ переключает и агента между ролями не рестартует —
# это обязанность оператора стенда (память [[ab-toggle-measures-the-restart]]:
# тумблер коллектора неотделим от рестарта, и переключать его молча внутри
# одного процесса значило бы измерять рестарт, а не TLS).
#
# ПОЧЕМУ СВЕРКА БИНАРЯ С ПРАВИЛАМИ — ОТДЕЛЬНЫЙ ШАГ. Манифест 23 TLS rule_id
# (item 1) обязан совпасть с rules/*.yaml, иначе объём окна 6.4.6
# отфильтруется не по тем правилам; выкат `rules/` без пересборки бинаря
# (правило item 6 постановки — `make generate && make build` перед прогоном)
# даёт агента с НУЛЁМ или неполным набором правил, и прогон напечатает не
# «TLS дал 0», а приборный ноль по каждой метке разом
# ([[rule-fields-and-binary-ship-together]]).
#
# Гигиена (память ebpf-guard-measurement-hygiene): чистый стор, рестарт
# больше чем за 1200 с до окна, никаких заходов на сервер внутри окна,
# никаких фоновых циклов на стенде. Контроли TLS (items 5/6 постановки) —
# ПОСЛЕ окна, вне /root/ (та же дисциплина, что item 3 волны 6.3.9.F).
#
# СМОК: SMOKE=1 гоняет ВСЕ ветки на коротких временах (пролог 60, окно 60,
# профиль 5). Ни один блок не пропускается — память
# smoke-only-does-not-cover-attack-window: смок, не покрывающий окно,
# стоил целого замера.
set -u
export PATH=$PATH:/usr/local/bin:/usr/local/go/bin
SETUP="${SETUP:-/opt/ebpf-guard/deploy/docker-test-setup}"
SVC="${SVC:-ebpf-guard-test.service}"
SMOKE="${SMOKE:-0}"
if [ "$SMOKE" = "1" ]; then
    PROLOGUE="${PROLOGUE:-60}"
    WINDOW="${WINDOW:-60}"
    ART="${ART:-/var/lib/w64-smoke-artifacts}"
    OUT="${OUT:-/root/run-6.4-smoke.log}"
    COLLECT="${COLLECT:-/root/collect-6.4-smoke}"
    DONE_MARK="${DONE_MARK:-/root/PIPELINE-6.4-SMOKE-DONE}"
    PROFILE_SECS="${PROFILE_SECS:-5}"
    # №432 (22.09.2026). Шапка обещает «ни один блок не пропускается», но
    # опорный набор item 3 умолчанием выключен, а его метки 6.3u.1…6.3u.6
    # стоят в W63_REQUIRED_LABELS БЕЗУСЛОВНО — поэтому смок дважды (21.09 и
    # 22.09) дошёл до стража и получил ОТКАЗ СОБРАТЬ АРХИВ на шести метках
    # без вердикта. То есть смок не мог подтвердить пайплайн целиком с того
    # дня, как эти метки завелись: ровно класс
    # [[smoke-only-does-not-cover-attack-window]]. Роль `check` переиспользует
    # базу с диска и добавляет к смоку секунды, а не минуты.
    W63_BASELINE_CONTROLS="${W63_BASELINE_CONTROLS:-check}"
else
    PROLOGUE="${PROLOGUE:-1800}"
    WINDOW="${WINDOW:-600}"
    ART="${ART:-/var/lib/w64-artifacts}"
    OUT="${OUT:-/root/run-6.4.log}"
    COLLECT="${COLLECT:-/root/collect-6.4}"
    DONE_MARK="${DONE_MARK:-/root/PIPELINE-6.4-DONE}"
    PROFILE_SECS="${PROFILE_SECS:-30}"
fi
NS="${NS:-w64}"
# ── АДРЕС API — ОДНОЙ ПЕРЕМЕННОЙ, А НЕ ПАРОЙ ПОДСТАНОВОК (правка 18.09.2026,
#    стоила запуска прогона B).
#
#    Было: "${VPS_IP:+http://${VPS_IP}:19090}${VPS_IP:-http://localhost:19090}"
#    — идиома, верная РОВНО пока VPS_IP пуст или содержит адрес. Запуск с
#    VPS_IP=localhost (совершенно законный: именно так зовутся контроли, см.
#    wave6.3-controls.sh:210) склеивает ОБЕ половины в
#    «http://localhost:19090localhost/metrics». curl молча отдаёт пустоту,
#    process_start_time_seconds читается пустым, и барьер готовности убивает
#    ЗДОРОВЫЙ прогон через 90 с после рестарта агента, напечатав «прогон
#    неизмерим» — тот же класс ложного «неизмеримо», что уже ловился у этого
#    барьера в №337. Адрес резолвится ОДИН раз, тем же способом, что у
#    контролей, и все пять мест читают его.
VPS_IP="${VPS_IP:-}"
W63_PIPE_API="${W63_PIPE_API:-http://${VPS_IP:-localhost}:19090}"
GATE_FORMULA="${GATE_FORMULA:-all}"
VERDICTS="${VERDICTS:-/root/wave6.3-controls-verdicts.txt}"

# ── ЛОГ ПРОГОНА ЗАХВАТЫВАЕТ САМ ПАЙПЛАЙН (правка 09.09.2026, найдена смоком).
#
# Шаг 4.5 кормит страж полноты файлом $OUT — «полным stdout controls.sh +
# пайплайна». Но НИКТО этот файл не создавал: он появлялся, только если
# оператор вручную завернул запуск в `| tee $OUT`. Запуск обычным способом
# (`nohup … >/dev/null &`) давал пустой $OUT, страж — «НЕИЗМЕРИМ: лог прогона
# пуст», и АРХИВ ОТКАЗЫВАЛСЯ СОБИРАТЬСЯ после целого прогона — при том что все
# 24 метки вердикт вынесли. То есть требование к запуску жило в голове
# оператора, а цена ошибки была в час стенда. Теперь пайплайн перезапускает
# сам себя под `tee`: $OUT существует всегда и содержит ровно то, что страж и
# должен читать. Флаг-страж от бесконечной рекурсии — W64_LOG_CAPTURED.
if [ -z "${W64_LOG_CAPTURED:-}" ]; then
    export W64_LOG_CAPTURED=1
    mkdir -p "$(dirname "$OUT")" 2>/dev/null
    # `tee` в конце конвейера, поэтому $? принадлежит ему, а не пайплайну —
    # настоящий код возврата проносится через файл. Имя файла своё на запуск:
    # фиксированное имя столкнуло бы два одновременных прогона (боевой и смок
    # на одном стенде — обычная пара) и вернуло бы чужой код.
    _w63_rcf=$(mktemp /tmp/.w626-rc.XXXXXX)
    { bash "$0" "$@" 2>&1; echo "$?" > "$_w63_rcf"; } | tee "$OUT"
    _w63_rc=$(cat "$_w63_rcf" 2>/dev/null || echo 1)
    rm -f "$_w63_rcf"
    exit "${_w63_rc:-1}"
fi

echo "=== ПРОГОН 6.4$([ "$SMOKE" = "1" ] && echo ' (СМОК)'), старт $(date -u +%FT%TZ) ==="
echo "пролог ${PROLOGUE}s, окно ${WINDOW}s, профиль ${PROFILE_SECS}s, формула гейта $GATE_FORMULA"

# ── Шаг 0. Реестры ДО прогона. ──────────────────────────────────────────────
# РЕЕСТР СУЖЕНИЙ ВОЛНЫ 6.3 (11 DNS-правил с ИЗМЕНЁННЫМ УСЛОВИЕМ, находка
# №329, new-rules.txt/W63_NARROWED_COND) СНЯТ ЦЕЛИКОМ в этом форке: items
# 1…7 постановки 6.4 правят Go-код TLS-коллектора (DynamicSymbols(), путь
# в mount-ns, симптом привязки) и добавляют МАНИФЕСТ, но НЕ меняют условие
# ни одного правила ни в одном YAML — new-rules.txt/renamed-rules.txt для
# волны 6.4 нечем заполнять, и жёсткий стоп по мёртвому реестру был бы
# ложным блоком прогона. Реестр idle-actors.txt (акторы фона ноды) и
# сторож осиротевших циклов ожидания ниже — ОБЩАЯ ГИГИЕНА измерения,
# применимая к любой волне, и остаются без изменений.
echo "--- реестры до прогона ---"
for f in idle-actors.txt new-rules.txt renamed-rules.txt silent-rules.txt; do
    _r63_found=0
    for d in "$SETUP/attacks" "$SETUP/scripts" "$SETUP" /opt/ebpf-guard/scripts; do
        if [ -f "$d/$f" ]; then
            echo "  $d/$f: $(wc -l < "$d/$f") строк"
            _r63_found=1
            break
        fi
    done
    [ "$_r63_found" -eq 1 ] || echo "  (нет: $f — не требуется волной 6.4, см. комментарий выше)"
done
W63_NODE_ACTORS_REQ="k3s-server coredns containerd containerd-shim iptables local-path-prov runc"
_r63_idle="$SETUP/attacks/idle-actors.txt"
_r63_gap=""
for _a in $W63_NODE_ACTORS_REQ; do
    grep -qE "^${_a}[[:space:]]" "$_r63_idle" 2>/dev/null || _r63_gap="$_r63_gap idle-actors.txt:$_a"
done
if [ -n "$_r63_gap" ]; then
    echo "СТОП ДО ПРОГОНА: реестр гигиены не заполнен:$_r63_gap"
    echo "  Атрибуция фона ноды неполна без него. Прогон не начат — агент не тронут, стор не очищен."
    exit 1
fi
echo "  реестр гигиены сверен: акторов ноды $(echo $W63_NODE_ACTORS_REQ | wc -w) в idle-actors.txt"

# Сторож гигиены (память ebpf-guard-measurement-hygiene, п.5): осиротевший
# цикл ожидания от прошлой сессии даёт весь фон замера себе. На прогоне 6.0.F
# два таких поллера дали 1195 совпадений/ч против 7/ч — 170×.
_r63_orph=$(ps -eo pid,ppid,etimes,args 2>/dev/null | awk '$2==1 && $3>300' | grep -cE 'until |while |pgrep ')
echo "  осиротевших фоновых циклов на стенде: $_r63_orph"
if [ "${_r63_orph:-0}" -gt 0 ]; then
    echo "СТОП ДО ПРОГОНА: на стенде $_r63_orph осиротевших циклов ожидания (ppid=1, >300с, until/while/pgrep)."
    ps -eo pid,ppid,etimes,args 2>/dev/null | awk '$2==1 && $3>300' | grep -E 'until |while |pgrep ' | sed 's/^/    /'
    echo "  Весь фон окна будет ИХ фоном, а не фоном ноды. Снять и перезапустить."
    exit 1
fi

# ── Шаг 0а — РЕТИРОВАН (волна 6.3.1, item 6, решение владельца 16.09.2026,
#    вариант ii). Раньше здесь стоял гейт AB_ENABLED=1 требующий пролог
#    ≥1200с: A/B dns.enabled перезапускал агента, и без пролога окно B мерило
#    бы обучение базы дрейфа, а не базовую линию (6.2.6.A). Разбор архива
#    collect-6.3-ab (16.09.2026, находки №335/№336) показал, что даже с этим
#    прологом A/B не измерял то, ради чего заводился: вклад DNS утонул в
#    конфаундерах рестарта (форсированное событие ноды только в окне A,
#    обнуление базы дрейфа). A/B удалён из wave6.3-controls.sh целиком;
#    6.3.4/6.3.5 теперь читают ось event_type внутри уже снятого тихого
#    окна, рестарта агента больше не требуют, и этот шаг стал мёртвым кодом.

# ── Шаг 0б (ITEM 8 постановки 6.4, по образцу №270). СТАТИЧЕСКАЯ СВЕРКА
#    ПОЛНОТЫ — ДО РЕСТАРТА АГЕНТА.
#    СВОЙ страж волны 6.4 (wave6.4-completeness-guard.sh, таблица
#    W64_REQUIRED_LABELS) — не старый 6.3.8. Тот же вопрос, заданный ДО
#    прогона: есть ли в тексте пайплайна строка, СПОСОБНАЯ вынести вердикт
#    по каждой метке ЭТОЙ постановки. Список файлов для --scan несёт СВОЙ
#    пайплайн (run-6.4-pipeline.sh) плюс унаследованные инструменты, чьи
#    тела всё ещё держат метки общей машинерии (wave6.3-controls.sh,
#    wave6.3-metrics-lib.sh — 6.2.6.*) и метку 6.4.7
#    (wave6.3.9f-item3-baseline-controls.sh — переиспользуется без
#    изменений, plan.md: «тот же прибор, что 6.3.9.5»). Проверка по логу
#    (Шаг 4.5) при этом остаётся: строка в скрипте может и не исполниться,
#    и только лог говорит, что вердикт РЕАЛЬНО вынесен.
echo "--- 6.4.8 (статическая сверка полноты, до прогона) ---"
if ! bash "$SETUP/wave6.4-completeness-guard.sh" --scan \
        "$SETUP/wave6.3-controls.sh" "$SETUP/run-6.4-pipeline.sh" "$SETUP/wave6.3-metrics-lib.sh" \
        "$SETUP/wave6.3.9f-item3-baseline-controls.sh"; then
    echo "СТОП ДО ПРОГОНА: пайплайн не покрывает таблицу меток постановки волны 6.4 (item 8, по образцу №269/№270)."
    echo "  Агент не тронут, стор не очищен — прогон не начат."
    exit 1
fi

# ── Шаг 0б2 (item 8 постановки 6.4, по образцу находки №373 волны 6.3.9.F).
#    ФИКСТУРНЫЙ ПРОГОН ВЕРДИКТНЫХ ВЕТОК — ТОЖЕ ДО РЕСТАРТА АГЕНТА.
#
#    Статическая сверка выше отвечает «строка есть». Метка, способная
#    напечатать только НЕИЗМЕРИМ (форма №373), прошла бы её насквозь.
#    wave6.4-emitter-fixtures.sh вынимает этот блок и исполняет его
#    на синтетических снимках, по ветке на исход, и отдельно спрашивает, умеет
#    ли КАЖДАЯ метка (кроме законно-постоянной 6.4.5) вынести годную величину
#    хоть на одном входе.
echo "--- сторож вердиктных веток 6.4.* (фикстурный прогон, до прогона) ---"
if ! bash "$SETUP/wave6.4-emitter-fixtures.sh"; then
    echo "СТОП ДО ПРОГОНА: вердиктные ветки меток 6.4.* не прошли фикстурный прогон (по образцу №373)."
    echo "  Агент не тронут, стор не очищен — прогон не начат."
    exit 1
fi

# ── Тот же довод для ОПОРНОГО НАБОРА (item 3), и только когда он просится.
