#    входа заведена (POST /api/v1/alerts/silence), и метка снимается двумя
#    подачами: базовым именем (обязано резолвиться в себя) и именем Rego
#    (обязано резолвиться в СВОИ базовые правила и НАЗВАТЬ их в ответе).
