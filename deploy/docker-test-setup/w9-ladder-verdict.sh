#!/bin/bash
# w9-ladder-verdict.sh <отчёт лестницы> [ещё файлы] — метки 8.8.1–8.8.7 и 9.6 ночи 9 (В6) из строк эмиттеров лестницы.
#
# Вход — строки «<метка> <роль>: PASS|FAIL|НЕИЗМЕРИМ — …» (w88-load-report.py, w88-att-verdict.sh, w88-hot-verdict.sh,
# w88-idle-verdict.sh). Выход — по строке на метку в формате сторожа полноты: «ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ: <метка> …».
#
# Сторож «не хуже 8.8»: эталон — вердикты ролей, которые несёт ночь (хост ×1 и под с limits.cpu из чарта = 1 ядро). У
# итоговой таблицы 8.8 (18.10) и финального бинаря волны 9 (n11, 20.10) там PASS по всем меткам, кроме 8.8.4 8.8 (перенесён
# в В8; на n11 — PASS по порогу 0,1% решения 3); значит, «не хуже» = PASS каждой обязательной роли.
#   ДОСТИГНУТО — у всех ролей метки PASS; ПРОВАЛЕН — хотя бы одна FAIL; НЕИЗМЕРИМ — иначе (роль без строки или НЕИЗМЕРИМ),
#   класс называется ролью.
# 9.6 (В6) — сводная: ДОСТИГНУТО, если 8.8.1–8.8.6 ДОСТИГНУТО; ПРОВАЛЕН, если хоть одна ПРОВАЛЕН; иначе НЕИЗМЕРИМ.
# Критерии эмиттера по решениям владельца 21.10: 8.8.4 — «0 событий» к полу калибровки; 8.8.3 — p99 только ×1; 8.8.2 ×N —
# по цене события (ночь несёт только ×1).
set -u
[ $# -ge 1 ] || { echo "usage: $0 <отчёт лестницы>..."; exit 2; }
IN=$(cat "$@" 2> /dev/null)
# метка → обязательные роли
REQ=("8.8.1:host pod" "8.8.2:host pod" "8.8.3:host pod" "8.8.4:host pod" "8.8.5:pod" "8.8.6:host" "8.8.6h:host" "8.8.7:idle")
role_word() { # role_word <метка> <роль> → PASS|FAIL|НЕИЗМЕРИМ|НЕТ
    local l=${1//./\\.} w
    w=$(printf '%s\n' "$IN" | grep -aE "^${l} $2: (PASS|FAIL|НЕИЗМЕРИМ)( |$)" | head -1 | sed -E "s/^[^:]*: ([A-ZА-Я]+).*/\1/")
    printf '%s' "${w:-НЕТ}"
}
role_detail() { local l=${1//./\\.}; printf '%s\n' "$IN" | grep -aE "^${l} $2: " | head -1 | sed -E 's/^[^—]*— ?//' | cut -c1-220; }
declare -A RES
for e in "${REQ[@]}"; do
    lbl=${e%%:*}; roles=${e#*:}; fail=""; unm=""; parts=""
    for r in $roles; do
        w=$(role_word "$lbl" "$r")
        parts="$parts; $r $w"
        case $w in
            PASS) ;;
            FAIL) fail="$fail; $r: $(role_detail "$lbl" "$r")" ;;
            НЕТ) unm="$unm; $r: нет строки эмиттера" ;;
            *) unm="$unm; $r: $(role_detail "$lbl" "$r")" ;;
        esac
    done
    if [ -n "$fail" ]; then v=ПРОВАЛЕН; why="хуже 8.8 (эталон PASS)${fail}"
    elif [ -n "$unm" ]; then v=НЕИЗМЕРИМ; why="класс НАЗВАН${unm}"
    else v=ДОСТИГНУТО; why="не хуже 8.8"; fi
    RES[$lbl]=$v
    echo "$v: $lbl ($why;${parts#;})"
done
# 9.6 — сводная по 8.8.1–8.8.6 (8.8.6h — часть 8.8.6)
f=""; u=""
for lbl in 8.8.1 8.8.2 8.8.3 8.8.4 8.8.5 8.8.6 8.8.6h; do
    case ${RES[$lbl]} in ПРОВАЛЕН) f="$f $lbl" ;; ДОСТИГНУТО) ;; *) u="$u $lbl" ;; esac
done
if [ -n "$f" ]; then echo "ПРОВАЛЕН: 9.6 (метки хуже 8.8:$f${u:+; неизмеримы:$u})"
elif [ -n "$u" ]; then echo "НЕИЗМЕРИМ: 9.6 (класс НАЗВАН: неизмеримы:$u)"
else echo "ДОСТИГНУТО: 9.6 (8.8.1–8.8.6 не хуже 8.8)"; fi
