#!/usr/bin/env bash
# wave6.2.2-metrics-lib.sh — измерительная половина волны 6.2.2, отдельным
# файлом и с собственным офлайн-сторожем.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Находки №238 и №239 — это не «контроль печатает не
# то», а «вход сужения слеп»: и список срезанных лимитером правил, и разбивка
# величины строились в `wave6.2.1-controls.sh` из СТОРОВОГО подмножества
# `_w621_new` (namespace непуст ИЛИ comm — нодовый актор). Сетевые и
# daemon-правила в это подмножество не попадают никогда, поэтому цикл по ним
# не выполнялся ни разу: прогон 6.2.1 напечатал «правила со срезом лимитера:
# нет» одновременно со срезом +530, а разбивка покрыла 14 из 322 алертов
# (4.3%). Обе функции ниже читают ТОЛЬКО метрики и о сторе ничего не знают.
#
# Файл самопроверяем: запуск
#
#   ./wave6.2.2-metrics-lib.sh --self-test ../../server-logs/collect-6.2.1
#
# прогоняет обе функции против двух срезов реального архива 6.2.1 и сверяет их
# с числами, зафиксированными критериями 6.2.2.2 и 6.2.2.3 в постановке ДО
# того, как код был написан: c2_periodic_beacon_pattern(+504),
# sigma_passwd_shadow_read_daemon(+26), покрытие разбивки ≥ 95% прямой дельты.
# Это тот самый сторож результата, которого у 6.2.1-версии не было: правка
# измерителя, не воспроизводящая известное число на известном архиве, — не
# починка, а вторая догадка поверх первой.
#
# Пайплайн 6.2.2 обязан взять эти функции отсюда (source), а не переписать их
# заново: у переписанной копии сторожа нет.

set -euo pipefail

# ---------------------------------------------------------------------------
# №238: поимённый список правил со срезом лимитера ЗА ОКНО — по МЕТРИКЕ.
#
# Перебираются rule_id из объединения имён в ОБОИХ срезах
# ebpf_guard_alerts_ratelimited_by_rule_total, а не из сторового списка.
# Печатает строки "rule_id +delta", по убыванию дельты; молчит, только если
# ни одно правило не срезано.
# ---------------------------------------------------------------------------
w622_ratelimited_by_rule() { # $1=срез-начало $2=срез-конец
    awk '
        function rid(line,   m) {
            if (match(line, /rule_id="[^"]*"/)) {
                m = substr(line, RSTART + 9, RLENGTH - 10)
                return m
            }
            return ""
        }
        FILENAME == ARGV[1] && /^ebpf_guard_alerts_ratelimited_by_rule_total[{ ]/ { a[rid($0)] = $NF }
        FILENAME == ARGV[2] && /^ebpf_guard_alerts_ratelimited_by_rule_total[{ ]/ { b[rid($0)] = $NF }
        END {
            for (r in b) if (r != "") { d = b[r] - (r in a ? a[r] : 0); if (d > 0) printf "%s %d\n", r, d }
            # Правило, исчезнувшее из второго среза, дельты не имеет — но и
            # молчать о нём нельзя: счётчик не убывает, исчезновение имени
            # означает рестарт агента внутри окна.
            for (r in a) if (r != "" && !(r in b)) printf "%s RESET\n", r
        }' "$1" "$2" | sort -k2 -rn
}

# ---------------------------------------------------------------------------
# №239: разбивка величины по правилам — по МЕТРИКЕ.
#
# Величина критерия 6.2.2.1 — это alerts_total + alerts_filtered_total (№227).
# Разбивка обязана суммироваться в неё же, иначе сужение работает вслепую
# (критерий 6.2.2.3: сумма разбивки ≥ 95% прямой дельты). Лейбла comm ни у
# одной из двух метрик нет, поэтому comm-срез остаётся сторовым и справочным —
# метрикой эту ось не восстановить.
# ---------------------------------------------------------------------------
w622_volume_by_rule() { # $1=срез-начало $2=срез-конец
    awk '
        function rid(line,   m) {
            if (match(line, /rule_id="[^"]*"/)) return substr(line, RSTART + 9, RLENGTH - 10)
            return ""
        }
        /^ebpf_guard_alerts_total[{ ]/ || /^ebpf_guard_alerts_filtered_total[{ ]/ {
            r = rid($0)
            if (r == "") next
            # Один rule_id встречается в нескольких строках (severity,
            # namespace, node…) — суммируются все.
            if (FILENAME == ARGV[1]) a[r] += $NF; else b[r] += $NF
        }
        END {
            for (r in b) { d = b[r] - (r in a ? a[r] : 0); if (d > 0) printf "%s %d\n", r, d }
        }' "$1" "$2" | sort -k2 -rn
}

# Прямая дельта объёма — та же формула, что у _w621_volume, повторена здесь,
# чтобы сторож ниже сверял разбивку с величиной, а не с самим собой.
w622_volume_delta() { # $1=срез-начало $2=срез-конец
    awk '
        /^ebpf_guard_alerts_total[{ ]/ || /^ebpf_guard_alerts_filtered_total[{ ]/ {
            if (FILENAME == ARGV[1]) a += $NF; else b += $NF
        }
        END { printf "%d", (b+0) - (a+0) }' "$1" "$2"
}

# ---------------------------------------------------------------------------
# Офлайн-сторож на архиве collect-6.2.1.
# ---------------------------------------------------------------------------
w622_self_test() { # $1=каталог архива
    local archive="${1:?путь к архиву, например server-logs/collect-6.2.1}"
    local s="$archive/controls/artifacts/metrics-window-start.txt"
    local e="$archive/controls/artifacts/metrics-window-end.txt"
    local rc=0

    for f in "$s" "$e"; do
        [ -s "$f" ] || { echo "СТОРОЖ ПРОВАЛЕН: нет среза $f"; return 1; }
    done

    echo "=== №238: правила со срезом лимитера за окно (по метрике) ==="
    local rl
    rl=$(w622_ratelimited_by_rule "$s" "$e")
    echo "$rl" | sed 's/^/    /'

    # Числа из постановки (критерий 6.2.2.2), записанные ДО разбора.
    local beacon passwd
    beacon=$(echo "$rl" | awk '$1=="c2_periodic_beacon_pattern"{print $2}')
    passwd=$(echo "$rl" | awk '$1=="sigma_passwd_shadow_read_daemon"{print $2}')
    if [ "${beacon:-0}" = "504" ]; then
        echo "  OK: c2_periodic_beacon_pattern(+504) — правило, которого сторовый цикл 6.2.1 не видел НИ РАЗУ"
    else
        echo "  ПРОВАЛ: ожидалось c2_periodic_beacon_pattern(+504), получено '${beacon:-нет}'"; rc=1
    fi
    if [ "${passwd:-0}" = "26" ]; then
        echo "  OK: sigma_passwd_shadow_read_daemon(+26)"
    else
        echo "  ПРОВАЛ: ожидалось sigma_passwd_shadow_read_daemon(+26), получено '${passwd:-нет}'"; rc=1
    fi
    if [ -z "$rl" ]; then
        echo "  ПРОВАЛ: пустой список при ненулевом срезе — это и есть дефект №238"; rc=1
    fi

    echo "=== №239: разбивка величины по правилам (по метрике) ==="
    local vol sum
    vol=$(w622_volume_delta "$s" "$e")
    sum=$(w622_volume_by_rule "$s" "$e" | awk '{s+=$2} END{printf "%d", s+0}')
    w622_volume_by_rule "$s" "$e" | head -12 | sed 's/^/    /'
    echo "  прямая дельта объёма: $vol; сумма разбивки: $sum"
    if [ "$vol" -le 0 ]; then
        echo "  ПРОВАЛ: прямая дельта объёма не положительна — архив не тот"; rc=1
    else
        local pct
        pct=$(awk -v s="$sum" -v v="$vol" 'BEGIN{printf "%.1f", 100.0*s/v}')
        echo "  покрытие разбивки: $pct% (критерий 6.2.2.3 требует ≥ 95%; версия 6.2.1 давала 4.3%)"
        awk -v s="$sum" -v v="$vol" 'BEGIN{exit !(s >= 0.95*v)}' || { echo "  ПРОВАЛ: разбивка не покрывает величину"; rc=1; }
    fi

    [ "$rc" -eq 0 ] && echo "СТОРОЖ ПРОЙДЕН" || echo "СТОРОЖ ПРОВАЛЕН"
    return "$rc"
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    case "${1:-}" in
        --self-test) shift; w622_self_test "${1:-}" ;;
        *) echo "использование: $0 --self-test <каталог архива>"; exit 2 ;;
    esac
fi
