#!/usr/bin/env bash
# wave6.2.6-completeness-guard.sh — ITEM 6 постановки волны 6.2.6 (находки
# №269/№270, критерий 6.2.6.18). ГЛАВНЫЙ ITEM ВОЛНЫ, обязан быть написан и
# самопроверен ПЕРВЫМ, до всякого другого кода пайплайна (plan.md, §6.2.6,
# «Порядок: item 6 — ПЕРВЫМ, до всякого кода»).
#
# ЧТО ЛЕЧИТ. Волна форкалась механически три раза подряд (6.2.2→6.2.3→
# 6.2.4) и трижды получала РАБОТАЮЩИЙ пайплайн предыдущей волны, который
# проходит `bash -n`/`--self-test`/офлайн-сторожи — все они проверяют
# УНАСЛЕДОВАННУЮ механику, ни один не проверяет ПОКРЫТИЕ постановки новой
# волны. Прогон 6.2.4 стартовал и дал 31 `OK` при двух провалах, хотя
# критерии 6.2.4.5/.6/.7/.12 не были реализованы вовсе, а вместо 6.2.4.6
# печатался старый 6.2.3.7 под чужой меткой (№269/№270) — ничто в пайплайне
# этого не заметило.
#
# КАК РАБОТАЕТ. Таблица меток постановки (REQUIRED) — константа в этом
# файле, синхронизируется руками с таблицей «Критерии 6.2.6» в plan.md при
# каждой правке постановки (это ЕДИНСТВЕННОЕ ручное звено; сторож проверяет
# СВОЮ таблицу, а не читает plan.md — Markdown не разбирается умышленно,
# чтобы страж не зависел от формата документа). Сторож читает лог прогона
# (run-6.2.6.log — полный stdout controls.sh + пайплайна, куда pass()/die()
# пишут "OK: <метка> ДОСТИГНУТО …" / "=== КОНТРОЛЬ ПРОВАЛЕН …: <метка>
# ПРОВАЛЕН/НЕИЗМЕРИМ …" — единственное полное место, см. wave6.2.6-controls.sh:
# W626_VERDICTS собирает только провалы) и для КАЖДОЙ метки REQUIRED ищет
# строку с этой ТОЧНОЙ меткой рядом с одним из трёх вердиктных слов
# (ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО). Отсутствие строки = метка НЕ ВЫНЕСЛА
# ВЕРДИКТ, вне зависимости от того, есть ли код критерия — ровно то отличие,
# которого не хватало №269 (код есть, вердикт печатается под ЧУЖОЙ меткой,
# значит СВОЯ метка отсутствует и обязана быть поймана). Четвёртое слово,
# ИЗМЕРЕНО, — для критериев БЕЗ ПОРОГА (правило 5.9.6: впервые измеренной
# величине порог не назначается, например 6.2.6.15/6.2.6.17/6.2.4.12): им
# нечего провалить или достичь, но метка обязана явно заявить, что снятие
# произошло, а не быть неотличимой от «не реализовано».
#
# ПОЧЕМУ НЕ ПАРСИТЬ plan.md АВТОМАТИЧЕСКИ. Разведано и отвергнуто: таблица
# «Критерии 6.2.6» в plan.md — прозаический markdown, не машиночитаемый
# контракт (столбцы содержат перенос строк, ссылки, code-span), и парсер
# сам стал бы источником такого же класса дефекта («сторож проверяет не то,
# что напечатано»). Ручная синхронизация константы с таблицей — тот же
# компромисс, что REQUIRED-список делает ЯВНЫМ и диффуется в git, а не
# прячется внутри парсера.
#
# ОТКАЗ СОБРАТЬ АРХИВ. w626_completeness_check возвращает ненулевой код при
# любом расхождении; run-6.2.6-pipeline.sh обязан остановить сборку архива
# на этом коде (см. правку в run-6.2.6-pipeline.sh) — расхождение НЕ
# предупреждение.
set -euo pipefail

# ---------------------------------------------------------------------------
# Таблица меток постановки волны 6.2.6 (plan.md, §6.2.6, «Критерии 6.2.6»).
# Четыре долговые метки (6.2.4.5/.6/.7/.12) НЕ переименованы намеренно
# (память criteria-index-pins-replay-labels) — метка "реализована под чужим
# номером" (№269: 6.2.3.7 вместо 6.2.4.6) обязана считаться ОТСУТСТВУЮЩЕЙ, и
# именно поэтому в этой таблице стоит 6.2.4.6, а не 6.2.3.7.
# ---------------------------------------------------------------------------
W626_REQUIRED_LABELS=(
    6.2.6.A 6.2.6.0 6.2.6.1 6.2.6.2 6.2.6.3 6.2.6.4
    6.2.4.5 6.2.4.6 6.2.4.7
    6.2.6.8 6.2.6.9 6.2.6.10 6.2.6.11
    6.2.4.12
    6.2.6.13 6.2.6.14 6.2.6.15 6.2.6.16 6.2.6.17 6.2.6.18
    6.2.6.19 6.2.6.20 6.2.6.21 6.2.6.22
)

# Экранирует метку для использования в grep -E (точки — буквальные).
_w626_guard_escape() { printf '%s' "$1" | sed 's/\./\\./g'; }

# w626_completeness_check <лог прогона>
# Печатает построчный отчёт по каждой метке; возвращает 0, только если
# КАЖДАЯ метка REQUIRED нашла хотя бы одну строку с вердиктным словом рядом
# с ней в логе. Печатает итоговый список отсутствующих меток и код "ОТКАЗ
# СОБРАТЬ АРХИВ" при расхождении.
w626_completeness_check() {
    local log="${1:?путь к логу прогона (run-6.2.6.log)}"
    local missing=() found=() lbl esc pattern hit
    [ -s "$log" ] || { echo "СТОРОЖ ПОЛНОТЫ: НЕИЗМЕРИМ — лог прогона пуст или отсутствует: $log"; return 2; }

    echo "=== 6.2.6.18: страж полноты пайплайна — сверка ${#W626_REQUIRED_LABELS[@]} меток постановки ==="
    for lbl in "${W626_REQUIRED_LABELS[@]}"; do
        # СОБСТВЕННАЯ МЕТКА СТРАЖА ищется не в логе, а выносится им самим —
        # иначе критерий 6.2.6.18 недостижим ПО ПОСТРОЕНИЮ: страж читает лог
        # ДО того, как его собственная вердиктная строка в этот лог попадёт,
        # и любой живой прогон получал бы «ОТКАЗ СОБРАТЬ АРХИВ: 6.2.6.18 без
        # вердикта». Синтетические фикстуры --self-test этого не показывали:
        # они содержат строку 6.2.6.18 заранее (фикстура 5 ниже закрывает
        # именно эту дыру). Метка остаётся в таблице REQUIRED — постановка
        # называет двадцать критериев, и вычёркивание одного из таблицы было
        # бы ровно тем расхождением, которое страж и ловит.
        if [ "$lbl" = "6.2.6.18" ]; then
            echo "    OK   $lbl: вердикт выносит сам страж последней строкой этой проверки"
            found+=("$lbl")
            continue
        fi
        esc=$(_w626_guard_escape "$lbl")
        pattern="(^|[^0-9.])${esc}([^0-9.]|\$).*(ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО)"
        if hit=$(grep -E "$pattern" "$log" | tail -1); then
            echo "    OK   $lbl: $(printf '%s' "$hit" | cut -c1-160)"
            found+=("$lbl")
        else
            echo "    НЕТ  $lbl: вердиктная строка не найдена"
            missing+=("$lbl")
        fi
    done

    echo "  меток с вердиктом: ${#found[@]}/${#W626_REQUIRED_LABELS[@]}"
    if [ "${#missing[@]}" -gt 0 ]; then
        echo "6.2.6.18 ОТКАЗ СОБРАТЬ АРХИВ: ${#missing[@]} меток постановки без вердикта: ${missing[*]}"
        echo "  (метка, реализованная под ЧУЖИМ номером, — как 6.2.3.7 вместо 6.2.4.6 в архиве 6.2.4 — считается отсутствующей: №269/№270)"
        return 1
    fi
    echo "6.2.6.18 ДОСТИГНУТО: все ${#W626_REQUIRED_LABELS[@]} меток постановки вынесли вердикт — архив разрешён к сборке"
    return 0
}

# ---------------------------------------------------------------------------
# СТАТИЧЕСКАЯ СВЕРКА (--scan). Тот же вопрос, что и у w626_completeness_check,
# заданный на СУТКИ РАНЬШЕ: не «вынес ли прогон вердикт по каждой метке», а
# «есть ли в тексте пайплайна строка, способная его вынести». Смысл ровно в
# цене ошибки: проверка по логу ловит неполноту ПОСЛЕ прогона (пролог 1800 с
# + окно 600 с + позитивные контроли — час стенда), статическая — ДО первой
# секунды. Форк, унаследовавший механику предыдущей волны и не получивший
# новых критериев (№270), падает здесь.
#
# Это НЕ замена проверке по логу: строка в скрипте может не исполниться
# (ветка INSTRUMENTED, die выше по потоку), и только лог говорит, что
# вердикт РЕАЛЬНО вынесен. Обе проверки нужны, и обе читают одну таблицу.
# ---------------------------------------------------------------------------
w626_completeness_scan() { # $@ = файлы пайплайна (controls/pipeline/lib)
    local missing=() lbl esc pattern f found
    [ "$#" -ge 1 ] || { echo "СТАТИЧЕСКАЯ СВЕРКА: не переданы файлы пайплайна"; return 2; }
    for f in "$@"; do
        [ -r "$f" ] || { echo "СТАТИЧЕСКАЯ СВЕРКА: нечитаем $f"; return 2; }
    done
    echo "=== 6.2.6.18 (статическая сверка ДО прогона): ${#W626_REQUIRED_LABELS[@]} меток против $# файлов пайплайна ==="
    for lbl in "${W626_REQUIRED_LABELS[@]}"; do
        # Метка стража — его собственная, её выносит этот файл (см. ниже).
        if [ "$lbl" = "6.2.6.18" ]; then continue; fi
        esc=$(_w626_guard_escape "$lbl")
        pattern="(^|[^0-9.])${esc}([^0-9.]|\$).*(ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО)"
        found=0
        for f in "$@"; do
            grep -qE "$pattern" "$f" && { found=1; break; }
        done
        if [ "$found" -eq 1 ]; then
            echo "    OK   $lbl: вердиктная строка есть в тексте пайплайна"
        else
            echo "    НЕТ  $lbl: НИ ОДНА строка пайплайна не способна вынести вердикт по этой метке"
            missing+=("$lbl")
        fi
    done
    if [ "${#missing[@]}" -gt 0 ]; then
        echo "6.2.6.18 СТАТИЧЕСКАЯ СВЕРКА ПРОВАЛЕНА: ${#missing[@]} меток постановки не реализованы: ${missing[*]}"
        echo "  Прогон не начат — час стенда не тратится на измерение, которое заведомо неполно (№270)."
        return 1
    fi
    echo "6.2.6.18 статическая сверка пройдена: каждая метка постановки имеет вердиктную строку в пайплайне"
    return 0
}

# ---------------------------------------------------------------------------
# --self-test. Строит СИНТЕТИЧЕСКИЕ логи (не требует стенда — контракт
# gate-offline-replay-on-mac) и проверяет три формы:
#   1) полный лог со всеми метками — сторож обязан ПРОЙТИ;
#   2) лог с одной строкой удалённой ("сняли реализацию, оставили метку в
#      таблице") — сторож обязан ПРОВАЛИТЬ и назвать ИМЕННО эту метку;
#   3) лог, где ОДНА строка вердикта напечатана под ЧУЖИМ номером — форма
#      находки №269 (6.2.3.7 вместо 6.2.4.6) — сторож обязан считать
#      требуемую метку ОТСУТСТВУЮЩЕЙ, а не спутать её с чужим номером.
# ---------------------------------------------------------------------------
w626_guard_self_test() {
    local rc=0 tmp
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' RETURN

    # --- фикстура 1: полный лог -------------------------------------------------
    local full="$tmp/full.log"
    : > "$full"
    local lbl
    for lbl in "${W626_REQUIRED_LABELS[@]}"; do
        echo "OK: $lbl ДОСТИГНУТО: синтетический вердикт самопроверки" >> "$full"
    done
    echo "=== ТЕСТ 1: полный лог, все метки вынесли вердикт ==="
    if w626_completeness_check "$full" >/tmp/w626_guard_t1.out 2>&1; then
        echo "  OK: сторож ПРОШЁЛ на полном логе, как и требуется"
    else
        echo "  ПРОВАЛ: сторож отказал на ПОЛНОМ логе — ложный отрицательный (см. /tmp/w626_guard_t1.out)"; rc=1
    fi

    # --- фикстура 2: "сняли реализацию, оставили метку" --------------------
    local dropped="$tmp/dropped.log"
    grep -v '6\.2\.6\.11 ' "$full" > "$dropped"
    echo "=== ТЕСТ 2 (мутация «снять реализацию 6.2.6.11, оставить метку»): страж обязан ПРОВАЛИТЬ ==="
    if out=$(w626_completeness_check "$dropped" 2>&1); then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ на логе с вырезанной 6.2.6.11 — мутация не поймана"; rc=1
    else
        if printf '%s' "$out" | grep -q '6\.2\.6\.11'; then
            echo "  OK: сторож ПРОВАЛИЛ и назвал именно 6.2.6.11 отсутствующей"
        else
            echo "  ПРОВАЛ: сторож провалился, но не назвал 6.2.6.11 отсутствующей"; rc=1
        fi
    fi

    # --- фикстура 3: метка реализована под ЧУЖИМ номером (форма №269) ------
    local renumbered="$tmp/renumbered.log"
    sed 's/^OK: 6\.2\.4\.6 /OK: 6.2.3.7 /' "$full" > "$renumbered"
    echo "=== ТЕСТ 3 (мутация №269: 6.2.4.6 напечатан как 6.2.3.7): страж обязан считать 6.2.4.6 ОТСУТСТВУЮЩЕЙ ==="
    if out=$(w626_completeness_check "$renumbered" 2>&1); then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ, хотя 6.2.4.6 нигде не напечатана под своим номером — форма №269 не поймана"; rc=1
    else
        if printf '%s' "$out" | grep -q '6\.2\.4\.6'; then
            echo "  OK: сторож ПРОВАЛИЛ и назвал 6.2.4.6 отсутствующей — метка под чужим номером не засчиталась"
        else
            echo "  ПРОВАЛ: сторож провалился НЕ по 6.2.4.6 — расследовать вывод: $out"; rc=1
        fi
    fi

    # --- фикстура 4: пустой лог — НЕИЗМЕРИМ, не «прошёл» и не «провалил молча» ---
    echo "=== ТЕСТ 4: пустой лог прогона ==="
    : > "$tmp/empty.log"
    if w626_completeness_check "$tmp/empty.log" >/tmp/w626_guard_t4.out 2>&1; then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ на пустом логе"; rc=1
    else
        echo "  OK: сторож НЕ прошёл на пустом логе (НЕИЗМЕРИМ)"
    fi

    # --- фикстура 5: лог БЕЗ собственной метки стража ----------------------
    # Форма ЖИВОГО прогона: страж читает лог до того, как напечатает свою
    # вердиктную строку, поэтому 6.2.6.18 в этом логе физически быть не может.
    # Фикстуры 1–4 содержали её заранее и потому не показывали, что критерий
    # 6.2.6.18 недостижим по построению. Страж обязан ПРОЙТИ на таком логе —
    # и обязан по-прежнему провалиться, если не хватает ЧУЖОЙ метки (это
    # проверяет фикстура 2, здесь проверяется только своя).
    local nosel="$tmp/no-self.log"
    grep -v '6\.2\.6\.18 ' "$full" > "$nosel"
    echo "=== ТЕСТ 5 (форма живого прогона: своей метки 6.2.6.18 в логе ещё нет): страж обязан ПРОЙТИ ==="
    if w626_completeness_check "$nosel" >/tmp/w626_guard_t5.out 2>&1; then
        echo "  OK: страж не требует собственной метки из лога — критерий 6.2.6.18 достижим на живом прогоне"
    else
        echo "  ПРОВАЛ: страж отказал только потому, что в логе нет ЕГО СОБСТВЕННОЙ строки — критерий недостижим по построению (см. /tmp/w626_guard_t5.out)"; rc=1
    fi

    rm -f /tmp/w626_guard_t1.out /tmp/w626_guard_t4.out /tmp/w626_guard_t5.out
    [ "$rc" -eq 0 ] && echo "САМОПРОВЕРКА 6.2.6.18 ПРОЙДЕНА" || echo "САМОПРОВЕРКА 6.2.6.18 ПРОВАЛЕНА"
    return "$rc"
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    case "${1:-}" in
        --self-test) w626_guard_self_test ;;
        --check) shift; w626_completeness_check "${1:?использование: $0 --check <run-6.2.6.log>}" ;;
        --scan)  shift; w626_completeness_scan "$@" ;;
        *) echo "использование: $0 --self-test | --check <run-6.2.6.log> | --scan <файлы пайплайна…>"; exit 2 ;;
    esac
fi
