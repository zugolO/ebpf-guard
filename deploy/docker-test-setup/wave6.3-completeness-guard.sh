# Экранирует метку для использования в grep -E (точки — буквальные).
_w63_guard_escape() { printf '%s' "$1" | sed 's/\./\\./g'; }

# ═════════════════════════════════════════════════════════════════════════════
# ITEM 9 (волна 6.3.1, побочная находка при item 7/№338) — КЛАСС ВЕРДИКТА, А НЕ
# «ВЕРДИКТ ЕСТЬ».
#
# До этой правки И `--check`, И `--scan` печатали ОДНО слово — «OK» — как
# только рядом с меткой находилась ЛЮБАЯ из четырёх вердиктных форм
# (ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО). Смок 15.09.2026 показал ровно
# цену этого: страж печатал `OK   6.3.6: === КОНТРОЛЬ ПРОВАЛЕН ===` — строка,
# читаемая глазами владельца при закрытии волны как «6.3.6 успешно», хотя
# счётчик `${#found[@]}/${#W63_REQUIRED_LABELS[@]}` в этот момент считает
# «вердикт вынесен», а не «критерий взят», и путаница этих двух вопросов
# ровно та форма ложного PASS, которую страж полноты и заводился ловить у
# ДРУГИХ критериев ([[subclause-verdicts-poison-label-registry]]).
#
# Классификация — по СОДЕРЖАНИЮ найденной строки, тем же порядком, что и у
# самого рантайма (`pass`/`die`/`notreq` в wave6.3-controls.sh): `notreq()`
# ВСЕГДА печатает «НЕ ЗАПРОШЕН» рядом с вердиктным словом (даже когда это
# слово — НЕИЗМЕРИМ), и это единственный надёжный маркер третьего состояния;
# `die()` пишет FAIL для ОБОИХ слов ПРОВАЛЕН и НЕИЗМЕРИМ одинаково (оба —
# отказ вынести годную величину); `pass()` — ДОСТИГНУТО/ИЗМЕРЕНО. Функция
# используется ОБЕИМИ проверками, чтобы классы не разошлись между `--scan`
# (текст пайплайна) и `--check` (текст лога).
#
# ЭТО НЕ МЕНЯЕТ СЕМАНТИКУ КРИТЕРИЯ 6.3.8. Существование вердикта (found/missing,
# «ОТКАЗ СОБРАТЬ АРХИВ») по-прежнему не зависит от класса — метка,
# провалившая свой критерий, всё равно «вынесла вердикт» и не роняет 6.3.8 (у
# него другая работа — ловить МОЛЧАНИЕ, а не провал; провал ловят сами
# критерии). Меняется только НАДПИСЬ рядом с меткой в отчёте: OK/FAIL/NOTREQ
# вместо безусловного OK.
# ═════════════════════════════════════════════════════════════════════════════
_w63_guard_classify() { # $1 = найденная строка (лог или исходный текст)
    local t="$1"
    if printf '%s' "$t" | grep -q 'ЗАПРОШЕН'; then
        echo NOTREQ
    elif printf '%s' "$t" | grep -qE 'ПРОВАЛЕН|НЕИЗМЕРИМ'; then
        echo FAIL
    elif printf '%s' "$t" | grep -qE 'ДОСТИГНУТО|ИЗМЕРЕНО'; then
        echo OK
    else
        echo '?'
    fi
}

# w63_completeness_check <лог прогона>
# Печатает построчный отчёт по каждой метке; возвращает 0, только если
# КАЖДАЯ метка REQUIRED нашла хотя бы одну строку с вердиктным словом рядом
# с ней в логе. Печатает итоговый список отсутствующих меток и код "ОТКАЗ
# СОБРАТЬ АРХИВ" при расхождении.
w63_completeness_check() {
    local log="${1:?путь к логу прогона (run-6.3.log)}"
    # ВТОРОЙ, НЕОБЯЗАТЕЛЬНЫЙ АРГУМЕНТ — реестр emitted-labels.txt, который
    # рантайм (`_w63_record_label` в wave6.3-controls.sh) пишет САМ, строками
    # «<метка> OK|FAIL|NOTREQ». Когда он передан, класс берётся ОТТУДА, а не
    # восстанавливается регэкспом по тексту вердикта: эвристика по словам
    # (ЗАПРОШЕН/ПРОВАЛЕН/НЕИЗМЕРИМ/ДОСТИГНУТО) верна ровно до первого
    # критерия, чьё ОБЪЯСНЕНИЕ упомянет чужое вердиктное слово — открытый
    # вопрос 2 item 9, закрытый здесь для проверки по логу (для --scan он
    # неустраним: реестра ещё нет, ничего не исполнялось).
    # Существование вердикта (found/missing, критерий 6.3.8) по-прежнему
    # определяется ТОЛЬКО логом: реестр отвечает на вопрос «каким классом», а
    # не «заговорила ли метка» — иначе страж перестал бы ловить метку, которая
    # записалась в реестр, но в лог не напечаталась.
    local registry="${2:-}"
    local missing=() found=() lbl esc pattern hit cls reg_cls
    [ -s "$log" ] || { echo "СТОРОЖ ПОЛНОТЫ: НЕИЗМЕРИМ — лог прогона пуст или отсутствует: $log"; return 2; }

    # №309: валидность UTF-8 печатается СЛОВОМ, а не предполагается. `grep -a`
    # выше уже защищает саму проверку меток от слепоты BSD grep, но офлайн-
    # разбор архива людьми обычно НЕ добавляет -a по привычке — строка ниже
    # обязана предупредить прежде, чем кто-то прочитает пустой grep как «в
    # логе этого нет».
    if command -v iconv >/dev/null 2>&1; then
        if iconv -f UTF-8 -t UTF-8 "$log" >/dev/null 2>&1; then
            echo "  СТОРОЖ №309: $log ВАЛИДЕН В UTF-8 — обычный grep/sed офлайн безопасен"
        else
            echo "  СТОРОЖ №309: $log НЕВАЛИДЕН В UTF-8 — офлайн-разбор ОБЯЗАН использовать grep -a (BSD grep на mac иначе молча не находит НИЧЕГО и не возвращает ошибку)"
        fi
    fi

    echo "=== 6.3.8: страж полноты пайплайна — сверка ${#W63_REQUIRED_LABELS[@]} меток постановки ==="
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        # СОБСТВЕННАЯ МЕТКА СТРАЖА ищется не в логе, а выносится им самим —
        # иначе критерий 6.3.8 недостижим ПО ПОСТРОЕНИЮ: страж читает лог
        # ДО того, как его собственная вердиктная строка в этот лог попадёт,
        # и любой живой прогон получал бы «ОТКАЗ СОБРАТЬ АРХИВ: 6.3.8 без
        # вердикта». Синтетические фикстуры --self-test этого не показывали:
        # они содержат строку 6.3.8 заранее (фикстура 5 ниже закрывает
        # именно эту дыру). Метка остаётся в таблице REQUIRED — постановка
        # называет двадцать критериев, и вычёркивание одного из таблицы было
        # бы ровно тем расхождением, которое страж и ловит.
        if [ "$lbl" = "6.3.8" ]; then
            printf '    %s  %s: %s\n' "OK" "$lbl" "вердикт выносит сам страж последней строкой этой проверки"
            found+=("$lbl")
            continue
        fi
        esc=$(_w63_guard_escape "$lbl")
        pattern="(^|[^0-9.])${esc}[[:space:]]+(ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО)"
        # №309: `grep -a` обязателен — без него BSD grep (mac) объявляет
        # невалидный-UTF-8 лог двоичным и молча не находит НИЧЕГО, что
        # неотличимо от «метки в логе нет». `cut -c` резал БАЙТАМИ и рвал
        # кириллицу пополам; substring по символам — через bash (multibyte
        # substring в bash — по символам в UTF-8-локали, а не по байтам).
        if hit=$(grep -aE "$pattern" "$log" | tail -1); then
            # item 9 (№338 побочно): класс вердикта, а не «вердикт есть» —
            # OK/FAIL/NOTREQ по содержанию самой найденной строки, см.
            # _w63_guard_classify выше. Существование (found/missing) не
            # зависит от класса — критерий 6.3.8 ловит МОЛЧАНИЕ, не провал.
            cls=$(_w63_guard_classify "$hit")
            if [ -n "$registry" ] && [ -s "$registry" ]; then
                # ПОСЛЕДНЯЯ запись метки в реестре — тот же выбор, что `tail -1`
                # по логу выше: критерий может вынести подпунктные вердикты
                # раньше главного (они пишутся под ключом «<метка>/подпункт» и
                # сюда не попадают), а повторный главный вердикт означает
                # перевынесение.
                reg_cls=$(awk -v l="$lbl" '$1 == l { c = $2 } END { print c }' "$registry" 2>/dev/null)
                if [ -n "${reg_cls:-}" ]; then
                    if [ "$reg_cls" != "$cls" ]; then
                        printf '    %s  %s: %s\n' "$reg_cls" "$lbl" "[реестр: $reg_cls ≠ текст лога: $cls — читать реестр] ${hit:0:120}"
                        cls="$reg_cls"
                        found+=("$lbl")
                        continue
                    fi
                    cls="$reg_cls"
                fi
            fi
            printf '    %s  %s: %s\n' "$cls" "$lbl" "${hit:0:160}"
            found+=("$lbl")
        else
            printf '    %s  %s: %s\n' "НЕТ" "$lbl" "вердиктная строка не найдена"
            missing+=("$lbl")
        fi
    done

    echo "  меток с вердиктом: ${#found[@]}/${#W63_REQUIRED_LABELS[@]}"
    if [ "${#missing[@]}" -gt 0 ]; then
        echo "6.3.8 ОТКАЗ СОБРАТЬ АРХИВ: ${#missing[@]} меток постановки без вердикта: ${missing[*]}"
        echo "  (метка, реализованная под ЧУЖИМ номером, — как 6.2.3.7 вместо 6.2.4.6 в архиве 6.2.4 — считается отсутствующей: №269/№270)"
        return 1
    fi
    echo "6.3.8 ДОСТИГНУТО: все ${#W63_REQUIRED_LABELS[@]} меток постановки вынесли вердикт — архив разрешён к сборке"
    return 0
}

# ---------------------------------------------------------------------------
# СТАТИЧЕСКАЯ СВЕРКА (--scan). Тот же вопрос, что и у w63_completeness_check,
# заданный на СУТКИ РАНЬШЕ: не «вынес ли прогон вердикт по каждой метке», а
# «есть ли в тексте пайплайна строка, способная его вынести». Смысл ровно в
# цене ошибки: проверка по логу ловит неполноту ПОСЛЕ прогона (пролог 1800 с
# + окно 600 с + позитивные контроли — час стенда), статическая — ДО первой
# секунды. Форк, унаследовавший механику предыдущей волны и не получивший
# новых критериев (№270), падает здесь.
#
# Это НЕ замена проверке по логу: строка в скрипте может не исполниться
# (ветка INSTRUMENTED, die выше по потоку), и только лог говорит, что
# вердикт РЕАЛЬНО вынесен. Обе проверки нужны, и обе читают одну таблицу.
# ---------------------------------------------------------------------------
w63_completeness_scan() { # $@ = файлы пайплайна (controls/pipeline/lib)
    local missing=() lbl esc pattern f found body classes cls_line uniq_classes
    [ "$#" -ge 1 ] || { echo "СТАТИЧЕСКАЯ СВЕРКА: не переданы файлы пайплайна"; return 2; }
    for f in "$@"; do
        [ -r "$f" ] || { echo "СТАТИЧЕСКАЯ СВЕРКА: нечитаем $f"; return 2; }
    done
    echo "=== 6.3.8 (статическая сверка ДО прогона): ${#W63_REQUIRED_LABELS[@]} меток против $# файлов пайплайна ==="
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        # Метка стража — его собственная, её выносит этот файл (см. ниже).
        if [ "$lbl" = "6.3.8" ]; then continue; fi
        esc=$(_w63_guard_escape "$lbl")
        pattern="(^|[^0-9.])${esc}[[:space:]]+(ДОСТИГНУТО|ПРОВАЛЕН|НЕИЗМЕРИМ|ИЗМЕРЕНО)"
        found=0
        classes=""
        for f in "$@"; do
            # ТОЛЬКО ИСПОЛНЯЕМЫЕ СТРОКИ. Смок 15.09.2026: сверка объявила
            # 20/20, а прогон не вынес вердикта по 6.2.6.1 и 6.2.6.8 —
            # обе метки «нашлись» в том, что вердикта вынести не может:
            #   • КОММЕНТАРИЙ («6.2.6.1 подпункт (3) ДОСТИГНУТО» — рамка,
            #     объясняющая прошлую находку);
            #   • ФИКСТУРА САМОПРОВЕРКИ библиотеки (строки реестра меток,
            #     которые --self-test строит нарочно);
            #   • текст ЧУЖОГО вердикта, упоминающий метку в объяснении
            #     («Величина 6.2.6.1 срезана ПОТЕРЕЙ … НЕИЗМЕРИМО» внутри
            #     die 6.2.6.0) — форма №269 в чистом виде.
            # Первые две снимаются фильтром ниже, третья — тем, что вердиктное
            # слово обязано стоять ВПЛОТНУЮ к метке (см. $pattern выше).
            # `| grep -q` ЗДЕСЬ НЕЛЬЗЯ: файл читается под `set -o pipefail`,
            # а `grep -q` закрывает вход на ПЕРВОМ совпадении — верхние звенья
            # получают SIGPIPE (141), pipefail делает код всего конвейера
            # ненулевым, и НАЙДЕННАЯ метка читается как ненайденная. Проверено
            # живьём: первая редакция этой правки объявила «не реализованы»
            # 6.2.6.A/6.2.6.0/6.2.6.3, чьи вердикты стоят в файле и печатались
            # на прогоне. Отсюда: фильтрация в переменную, поиск — herestring.
            body=$(grep -vE '^[[:space:]]*#' "$f" | grep -v 'w63_label_key' || true)
            # item 9 (№338 побочно): НЕ останавливаться на первом совпадении.
            # Одна метка может иметь НЕСКОЛЬКО веток (pass в одной, die в
            # другой) — статическая сверка обязана назвать ВСЕ классы,
            # которые пайплайн способен вынести для этой метки, а не только
            # факт «строка есть» (это и была форма ложного PASS: «OK» рядом
            # с меткой читался как «критерий пройдёт», хотя единственная
            # найденная строка могла быть веткой ПРОВАЛЕН/НЕИЗМЕРИМ).
            while IFS= read -r cls_line; do
                [ -n "$cls_line" ] || continue
                found=1
                classes="$classes $(_w63_guard_classify "$cls_line")"
            done < <(grep -E "$pattern" <<< "$body" || true)
        done
        if [ "$found" -eq 1 ]; then
            uniq_classes=$(printf '%s\n' $classes | sort -u | tr '\n' ',' | sed 's/,$//')
            printf '    %s  %s: %s\n' "$uniq_classes" "$lbl" "вердиктная строка(и) в тексте пайплайна способны вынести: ${uniq_classes}"
        else
            printf '    %s  %s: %s\n' "НЕТ" "$lbl" "НИ ОДНА строка пайплайна не способна вынести вердикт по этой метке"
            missing+=("$lbl")
        fi
    done
    if [ "${#missing[@]}" -gt 0 ]; then
        echo "6.3.8 СТАТИЧЕСКАЯ СВЕРКА ПРОВАЛЕНА: ${#missing[@]} меток постановки не реализованы: ${missing[*]}"
        echo "  Прогон не начат — час стенда не тратится на измерение, которое заведомо неполно (№270)."
        return 1
    fi
    echo "6.3.8 статическая сверка пройдена: каждая метка постановки имеет вердиктную строку в пайплайне"
    return 0
}

# ---------------------------------------------------------------------------
# --self-test. Строит СИНТЕТИЧЕСКИЕ логи (не требует стенда — контракт
# gate-offline-replay-on-mac) и проверяет три формы:
#   1) полный лог со всеми метками — сторож обязан ПРОЙТИ;
#   2) лог с одной строкой удалённой ("сняли реализацию, оставили метку в
#      таблице") — сторож обязан ПРОВАЛИТЬ и назвать ИМЕННО эту метку;
#   3) лог, где ОДНА строка вердикта напечатана под ЧУЖИМ номером — форма
#      находки №269 (6.2.3.7 вместо 6.2.4.6) — сторож обязан считать
#      требуемую метку ОТСУТСТВУЮЩЕЙ, а не спутать её с чужим номером.
# ---------------------------------------------------------------------------
w63_guard_self_test() {
    local rc=0 tmp
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' RETURN

    # --- фикстура 1: полный лог -------------------------------------------------
    local full="$tmp/full.log"
    : > "$full"
    local lbl
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        echo "OK: $lbl ДОСТИГНУТО: синтетический вердикт самопроверки" >> "$full"
    done
    echo "=== ТЕСТ 1: полный лог, все метки вынесли вердикт ==="
    if w63_completeness_check "$full" >/tmp/w63_guard_t1.out 2>&1; then
        echo "  OK: сторож ПРОШЁЛ на полном логе, как и требуется"
    else
        echo "  ПРОВАЛ: сторож отказал на ПОЛНОМ логе — ложный отрицательный (см. /tmp/w63_guard_t1.out)"; rc=1
    fi

    # --- фикстура 2: "сняли реализацию, оставили метку" --------------------
    local dropped="$tmp/dropped.log"
    # Метка мутации обязана быть ИЗ ТАБЛИЦЫ ЭТОЙ волны: форк унаследовал
    # фикстуру на 6.2.6.11, которой в таблице 6.3 нет вовсе — `grep -v` не
    # удалял бы НИЧЕГО, страж законно проходил бы, и самопроверка объявляла бы
    # ПРОВАЛ на здоровом стороже (память self-test-fixtures-miss-live-log-shape).
    grep -v '6\.3\.2 ' "$full" > "$dropped"
    echo "=== ТЕСТ 2 (мутация «снять реализацию 6.3.2, оставить метку»): страж обязан ПРОВАЛИТЬ ==="
    if out=$(w63_completeness_check "$dropped" 2>&1); then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ на логе с вырезанной 6.3.2 — мутация не поймана"; rc=1
    else
        if printf '%s' "$out" | grep -q '6\.3\.2'; then
            echo "  OK: сторож ПРОВАЛИЛ и назвал именно 6.3.2 отсутствующей"
        else
            echo "  ПРОВАЛ: сторож провалился, но не назвал 6.3.2 отсутствующей"; rc=1
        fi
    fi

    # --- фикстура 3: метка реализована под ЧУЖИМ номером (форма №269) ------
    local renumbered="$tmp/renumbered.log"
    # Форма №269 в декорациях 6.3: критерий 6.3.6 — это и есть взятый долг
    # 6.2.6.16, и напечатать его под СТАРЫМ номером долга — самая вероятная
    # ошибка именно этой волны, а не гипотетическая.
    sed 's/^OK: 6\.3\.6 /OK: 6.2.6.16 /' "$full" > "$renumbered"
    echo "=== ТЕСТ 3 (мутация №269: 6.3.6 напечатан под старым номером долга 6.2.6.16): страж обязан считать 6.3.6 ОТСУТСТВУЮЩЕЙ ==="
    if out=$(w63_completeness_check "$renumbered" 2>&1); then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ, хотя 6.3.6 нигде не напечатана под своим номером — форма №269 не поймана"; rc=1
    else
        if printf '%s' "$out" | grep -q '6\.3\.6'; then
            echo "  OK: сторож ПРОВАЛИЛ и назвал 6.3.6 отсутствующей — метка под чужим номером не засчиталась"
        else
            echo "  ПРОВАЛ: сторож провалился НЕ по 6.3.6 — расследовать вывод: $out"; rc=1
        fi
    fi

    # --- фикстура 4: пустой лог — НЕИЗМЕРИМ, не «прошёл» и не «провалил молча» ---
    echo "=== ТЕСТ 4: пустой лог прогона ==="
    : > "$tmp/empty.log"
    if w63_completeness_check "$tmp/empty.log" >/tmp/w63_guard_t4.out 2>&1; then
        echo "  ПРОВАЛ: сторож ПРОШЁЛ на пустом логе"; rc=1
    else
        echo "  OK: сторож НЕ прошёл на пустом логе (НЕИЗМЕРИМ)"
    fi

    # --- фикстура 5: лог БЕЗ собственной метки стража ----------------------
    # Форма ЖИВОГО прогона: страж читает лог до того, как напечатает свою
    # вердиктную строку, поэтому 6.3.8 в этом логе физически быть не может.
    # Фикстуры 1–4 содержали её заранее и потому не показывали, что критерий
    # 6.3.8 недостижим по построению. Страж обязан ПРОЙТИ на таком логе —
    # и обязан по-прежнему провалиться, если не хватает ЧУЖОЙ метки (это
    # проверяет фикстура 2, здесь проверяется только своя).
    local nosel="$tmp/no-self.log"
    grep -v '6\.3\.8 ' "$full" > "$nosel"
    echo "=== ТЕСТ 5 (форма живого прогона: своей метки 6.3.8 в логе ещё нет): страж обязан ПРОЙТИ ==="
    if w63_completeness_check "$nosel" >/tmp/w63_guard_t5.out 2>&1; then
        echo "  OK: страж не требует собственной метки из лога — критерий 6.3.8 достижим на живом прогоне"
    else
        echo "  ПРОВАЛ: страж отказал только потому, что в логе нет ЕГО СОБСТВЕННОЙ строки — критерий недостижим по построению (см. /tmp/w63_guard_t5.out)"; rc=1
    fi

    # --- фикстура 6 (№309): лог с НЕВАЛИДНЫМ UTF-8 — метки ищутся, разрыв ---
    # называется словом. Байт 0xFF ни в одной кодировке не валиден; ставится
    # ОДНОЙ строкой в середину полного лога, а не поверх метки, чтобы страж
    # мог показать ОБА факта разом: метки по-прежнему находятся (grep -a
    # держит), а невалидность UTF-8 названа отдельной строкой.
    local badutf="$tmp/bad-utf8.log"
    { printf '%s\n' "мусорная строка перед разрывом"; printf '\xff\xfe разрыв UTF-8\n'; cat "$full"; } > "$badutf"
    echo "=== ТЕСТ 6 (№309: невалидный UTF-8 в логе): страж обязан НАЗВАТЬ разрыв и НЕ ослепнуть на метках ==="
    if out=$(w63_completeness_check "$badutf" 2>&1); then
        if printf '%s' "$out" | grep -q 'НЕВАЛИДЕН В UTF-8'; then
            echo "  OK: страж прошёл (все метки нашлись через grep -a) и явно назвал лог невалидным в UTF-8"
        else
            echo "  ПРОВАЛ: страж прошёл, но не назвал лог невалидным в UTF-8 — молчаливый разрыв (№309)"; rc=1
        fi
    else
        echo "  ПРОВАЛ: страж ОТКАЗАЛ на логе с невалидным UTF-8 — метки после разрыва не нашлись (BSD grep без -a ослеп бы так же)"; rc=1
    fi

    # --- фикстура 7: СТАТИЧЕСКАЯ СВЕРКА не считает вердиктом упоминание -------
    # Форма, снятая смоком на стенде 15.09.2026: --scan объявил 20/20, а прогон
    # не вынес вердикта по 6.2.6.1 и 6.2.6.8. Обе метки «нашлись» там, где
    # вердикта вынести нельзя: в КОММЕНТАРИИ, в ФИКСТУРЕ самопроверки и внутри
    # текста ЧУЖОГО вердикта. Ни одна синтетическая фикстура этого не ловила —
    # они проверяли только сверку ПО ЛОГУ (память
    # self-test-fixtures-miss-live-log-shape).
    local fakepipe="$tmp/fake-pipeline.sh"
    cat > "$fakepipe" <<'FAKE'
#!/bin/bash
# 6.3.2 ДОСТИГНУТО — это КОММЕНТАРИЙ, вердикта он не выносит
die "6.3.1 ПРОВАЛЕН: величина 6.3.2 при этом осталась НЕИЗМЕРИМОЙ"
echo "$(w63_label_key '6.3.2 ДОСТИГНУТО: фикстура реестра, не вердикт') OK"
FAKE
    echo "=== ТЕСТ 7 (--scan): комментарий, фикстура и чужой вердикт НЕ считаются реализацией ==="
    if out=$(w63_completeness_scan "$fakepipe" 2>&1); then
        echo "  ПРОВАЛ: статическая сверка ПРОШЛА на файле, где ни одна метка не выносит вердикта"; rc=1
    elif printf '%s' "$out" | grep -q 'НЕТ  6.3.2'; then
        echo "  OK: статическая сверка не засчитала ни комментарий, ни фикстуру, ни упоминание внутри чужого вердикта"
    else
        echo "  ПРОВАЛ: статическая сверка отказала, но 6.3.2 не названа отсутствующей"; rc=1
    fi
    # Обратная половина той же фикстуры: НАСТОЯЩАЯ вердиктная строка обязана
    # засчитываться — иначе сверка «проходит» только на пустом файле. Проверено
    # живьём: первая редакция правки роняла 6.2.6.A/6.2.6.0/6.2.6.3 из-за
    # SIGPIPE под pipefail, то есть ложным ПРОВАЛОМ вместо ложного PASS.
    printf '%s\n' 'pass "6.3.2 ДОСТИГНУТО: настоящая вердиктная строка"' >> "$fakepipe"
    if out=$(w63_completeness_scan "$fakepipe" 2>&1); then
        echo "  ПРОВАЛ: сверка прошла целиком — прочие метки в фикстуре не реализованы, пройти она не может"; rc=1
    elif printf '%s' "$out" | grep -q 'OK  6.3.2'; then
        echo "  OK: настоящая вердиктная строка засчитана (ложного ПРОВАЛА от pipefail/SIGPIPE нет)"
    else
        echo "  ПРОВАЛ: настоящая вердиктная строка 6.3.2 НЕ засчитана — сверка слепа к исполняемым строкам"; rc=1
    fi

    # --- фикстура 8 (item 9, №338 побочно): КЛАСС ВЕРДИКТА, А НЕ «ВЕРДИКТ
    # ЕСТЬ». Форма, найденная смоком 15.09.2026 в чистом виде: страж печатал
    # «OK   6.3.6: === КОНТРОЛЬ ПРОВАЛЕН ===», и «OK» рядом с провалившейся
    # меткой читался владельцем как успех. Лог ниже несёт ОДНУ метку с
    # настоящим ПРОВАЛЕН (через die(), как в реальном гарнессе) и ОДНУ с
    # НЕ ЗАПРОШЕН (как реальная ветка 6.3.5) — страж обязан напечатать рядом
    # с ними FAIL и NOTREQ соответственно, а не OK ни в одном из двух случаев.
    local classlog="$tmp/class.log"
    : > "$classlog"
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        case "$lbl" in
            6.3.6) echo "=== КОНТРОЛЬ ПРОВАЛЕН (прогон НЕ прерывается): $lbl ПРОВАЛЕН: синтетический провал самопроверки ===" >> "$classlog" ;;
            6.3.5) echo "НЕ ЗАПРОШЕН ПОСТАНОВКОЙ: $lbl НЕИЗМЕРИМ (НЕ ЗАПРОШЕН постановкой): синтетический NOTREQ самопроверки" >> "$classlog" ;;
            *) echo "OK: $lbl ДОСТИГНУТО: синтетический вердикт самопроверки" >> "$classlog" ;;
        esac
    done
    echo "=== ТЕСТ 8 (item 9: класс вердикта, а не «вердикт есть»): 6.3.6=ПРОВАЛЕН обязан читаться как FAIL, 6.3.5=NOTREQ как NOTREQ ==="
    out=$(w63_completeness_check "$classlog" 2>&1) || true
    if printf '%s' "$out" | grep -q 'FAIL  6.3.6'; then
        echo "  OK: 6.3.6 (ПРОВАЛЕН) напечатана как FAIL, а не как OK"
    else
        echo "  ПРОВАЛ: 6.3.6 (ПРОВАЛЕН) НЕ напечатана как FAIL — см. вывод: $out"; rc=1
    fi
    if printf '%s' "$out" | grep -q 'NOTREQ  6.3.5\|NOTREQ 6.3.5'; then
        echo "  OK: 6.3.5 (НЕ ЗАПРОШЕН) напечатана как NOTREQ, а не как OK/FAIL"
    else
        echo "  ПРОВАЛ: 6.3.5 (НЕ ЗАПРОШЕН) НЕ напечатана как NOTREQ — см. вывод: $out"; rc=1
    fi
    if printf '%s' "$out" | grep -qE 'OK  +6\.3\.6|OK  +6\.3\.5'; then
        echo "  ПРОВАЛ: 6.3.6 или 6.3.5 всё ещё напечатаны как OK — ровно форма находки №338"; rc=1
    fi

    # Та же проверка классов — статической сверкой (--scan): исходный текст
    # с ОДНОЙ веткой die (ПРОВАЛЕН) для метки обязан дать класс FAIL, а не OK.
    local failpipe="$tmp/fail-pipeline.sh"
    printf '%s\n' 'die "6.3.2 ПРОВАЛЕН: синтетическая ветка провала"' > "$failpipe"
    echo "=== ТЕСТ 8б (--scan, item 9): единственная ветка die() обязана дать класс FAIL ==="
    out=$(w63_completeness_scan "$failpipe" 2>&1) || true
    if printf '%s' "$out" | grep -q 'FAIL  6.3.2'; then
        echo "  OK: статическая сверка назвала класс FAIL, а не OK"
    else
        echo "  ПРОВАЛ: статическая сверка не назвала 6.3.2 классом FAIL — см. вывод: $out"; rc=1
    fi

    # --- фикстура 9: ПРЕФИКСНОЕ СТОЛКНОВЕНИЕ 6.3.1 vs 6.3.1.N ---------------
    # Волна 6.3.1 завела семь меток, чьи номера — расширение уже существующей
    # метки 6.3.1 (позитивный DNS-контроль). Если бы регэксп допускал точку
    # после метки, строка «6.3.1.1 ДОСТИГНУТО» засчиталась бы метке «6.3.1»,
    # и вырезанный позитивный контроль читался бы как вынесший вердикт —
    # форма №269 внутри одной волны. Лог ниже несёт ВСЕ семь подметок и НЕ
    # несёт 6.3.1: страж обязан назвать отсутствующей именно 6.3.1.
    local prefixlog="$tmp/prefix.log"
    : > "$prefixlog"
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        [ "$lbl" = "6.3.1" ] && continue
        echo "OK: $lbl ДОСТИГНУТО: синтетический вердикт самопроверки" >> "$prefixlog"
    done
    echo "=== ТЕСТ 9 (префиксное столкновение): 6.3.1.N не должны засчитываться метке 6.3.1 ==="
    if out=$(w63_completeness_check "$prefixlog" 2>&1); then
        echo "  ПРОВАЛ: страж ПРОШЁЛ на логе без 6.3.1 — подметки 6.3.1.N засчитались родительской метке"; rc=1
    elif printf '%s' "$out" | grep -qE 'ОТКАЗ СОБРАТЬ АРХИВ.*6\.3\.1( |$)'; then
        echo "  OK: страж назвал отсутствующей именно 6.3.1, подметки ей не засчитаны"
    else
        echo "  ПРОВАЛ: страж провалился, но не назвал 6.3.1 отсутствующей — см. вывод: $out"; rc=1
    fi

    # --- фикстура 10: КЛАСС ИЗ РЕЕСТРА, А НЕ ИЗ ТЕКСТА ----------------------
    # Открытый вопрос 2 item 9: классификация по подстрокам — эвристика.
    # Лог ниже содержит вердикт, чьё ОБЪЯСНЕНИЕ упоминает «ДОСТИГНУТО» после
    # вердиктного слова ПРОВАЛЕН, а реестр (который пишет сам рантайм) несёт
    # для этой метки FAIL. Страж с реестром обязан напечатать FAIL.
    local reglog="$tmp/reg.log" regfile="$tmp/emitted-labels.txt"
    : > "$reglog"; : > "$regfile"
    for lbl in "${W63_REQUIRED_LABELS[@]}"; do
        if [ "$lbl" = "6.3.3" ]; then
            echo "=== КОНТРОЛЬ ПРОВАЛЕН: $lbl ПРОВАЛЕН: величина не ДОСТИГНУТО порога ===" >> "$reglog"
            echo "$lbl FAIL" >> "$regfile"
        else
            echo "OK: $lbl ДОСТИГНУТО: синтетический вердикт самопроверки" >> "$reglog"
            echo "$lbl OK" >> "$regfile"
        fi
    done
    echo "=== ТЕСТ 10 (item 9, открытый вопрос 2): класс берётся из реестра рантайма, а не из слов текста ==="
    out=$(w63_completeness_check "$reglog" "$regfile" 2>&1) || true
    if printf '%s' "$out" | grep -q 'FAIL  6.3.3'; then
        echo "  OK: класс 6.3.3 взят из реестра как FAIL"
    else
        echo "  ПРОВАЛ: класс 6.3.3 не прочитан из реестра — см. вывод: $out"; rc=1
    fi
    # И обратная половина: без реестра страж обязан продолжать работать
    # (второй аргумент необязателен) — иначе правка ломает текущий пайплайн.
    out=$(w63_completeness_check "$reglog" 2>&1) || true
    if printf '%s' "$out" | grep -q '6.3.3'; then
        echo "  OK: без реестра проверка по логу по-прежнему работает"
    else
        echo "  ПРОВАЛ: без реестра проверка по логу сломалась — см. вывод: $out"; rc=1
    fi

    rm -f /tmp/w63_guard_t1.out /tmp/w63_guard_t4.out /tmp/w63_guard_t5.out
    [ "$rc" -eq 0 ] && echo "САМОПРОВЕРКА 6.3.8 ПРОЙДЕНА" || echo "САМОПРОВЕРКА 6.3.8 ПРОВАЛЕНА"
    return "$rc"
}

