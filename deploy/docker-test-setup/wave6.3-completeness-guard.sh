#
# ДВЕ ПРОВЕРКИ, ОДНА ТАБЛИЦА. `--scan` спрашивает то же самое на сутки раньше:
# есть ли в ТЕКСТЕ пайплайна строка, способная вынести вердикт. Проверка по
