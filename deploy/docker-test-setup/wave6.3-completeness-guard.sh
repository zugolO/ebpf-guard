    case "${1:-}" in
        --self-test) w63_guard_self_test ;;
        --check) shift; w63_completeness_check "${1:?использование: $0 --check <run-6.3.log> [emitted-labels.txt]}" "${2:-}" ;;
        --scan)  shift; w63_completeness_scan "$@" ;;
        *) echo "использование: $0 --self-test | --check <run-6.3.log> [emitted-labels.txt] | --scan <файлы пайплайна…>"; exit 2 ;;
    esac
fi
