# ТРЕБОВАТЬ ЕГО ЗНАЧИТ ПРОВАЛИВАТЬ ПРОГОН ЗА ИСПРАВНУЮ РАБОТУ.
#
# Опорный снимок берётся ОДНИМ `curl /metrics`, и это чтение само поднимает
# алерты (`sensitive_file_read` на путях, которые читает экспортёр). Их отметки
# времени попадают в сторовый интервал [опорный снимок, t1), но в МЕТРИЧЕСКИЙ
# снимок, полученный ЭТИМ ЖЕ чтением, попасть не могут по причинно-следственной
# связи. Остаток поэтому тождественно равен МИНУС цене опорного чтения, и это
# снято дважды 15.09.2026: смок −2 и боевой прогон −2, оба раза ровно два
# `curl sensitive_file_read`.
#
# Сторож поэтому сверяет остаток не с нулём, а с ПРЯМЫМ ЧИСЛОМ цены опорного
# чтения по дереву — той же осью, что и №320. Ноль остаётся законным исходом
# (если алерты чтения не успели к t1 сторового окна), но перестаёт быть
# ЕДИНСТВЕННЫМ законным ([[verdict-zero-needs-its-class-presented]]).
# ═════════════════════════════════════════════════════════════════════════════
_w63_ref_read_cost=0
if [ "${_w63_read_cost_measurable:-0}" -eq 1 ]; then
