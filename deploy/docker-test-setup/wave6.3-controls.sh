# Журнальный счётчик потерь (№222, второй слой). №240: журнал читается ОТ
# СТАРТА АГЕНТА, а не за всю историю юнита — иначе величина принадлежит
# прошлым прогонам.
# 6.2.9.F.4 (№294, item 4 волны 6.2.9.F): СТОРОЖ ПОТЕРЬ НА ГРАНИЦАХ ОКОН
# ПОДАЧИ, А НЕ ТОЛЬКО ТИХОГО ОКНА. До этой правки потери снимались только на
# границах [t0,t1] (6.2.6.A/6.2.6.0) — окна ПОДАЧИ (старты подов, побег,
# инициализация контейнера) мерились на приборе, который мог терять события
# незамеченно: журнал первого прогона показал 111 fileaccess/ringbuf_to_router
# внутри окна стартов подов и 645 syscall/ringbuf_to_router внутри окна
# подачи 6.2.6.16, и вердикты этих окон печатались без единого слова о
# потерях — «21,7 алертов/под» была нижней оценкой, объявленной измеренной.
# Печатает разбивку {collector,reason} между двумя снимками окна подачи;
# устанавливает _W63_LOSS_NONZERO=1, если суммарная дельта потерь (без
# path_denylist) ненулевая — вызывающая сторона обязана добавить в свой
# вердикт явное слово «НИЖНЯЯ ОЦЕНКА», а не молчать о потерях, как раньше.
#
# ИМЯ ОКНА ПЕРЕДАЁТСЯ БЕЗ НОМЕРА КРИТЕРИЯ. Строка этого сторожа несёт
# вердиктное слово, и метка чужого критерия внутри неё была бы прочитана
# стражем полноты (6.2.6.18 матчит «<метка> … (ДОСТИГНУТО|ПРОВАЛЕН|
# НЕИЗМЕРИМ|ИЗМЕРЕНО)» по всей строке) как вынесенный вердикт ПО ЧУЖОЙ
# МЕТКЕ — тот же класс ложного PASS, что №269. Номера критериев остаются в
# комментариях у call-site'ов.
#
# ОТСУТСТВУЮЩИЙ СНИМОК — НЕИЗМЕРИМОСТЬ, А НЕ НОЛЬ. `_w63_real_drops` при
# нечитаемом файле молча падает на ЖИВОЕ чтение /metrics (ветка `|| _w63_metrics`
# в её определении выше), и дельта двух живых чтений дала бы «потерь нет» на
# прогоне, где снимок просто не был снят. Файлы проверяются явно.
_w63_submission_loss_guard() { # $1=имя окна (БЕЗ номера критерия) $2=файл-начало $3=файл-конец
    local label="$1" f0="$2" f1="$3" d
    if [ ! -s "$f0" ] || [ ! -s "$f1" ]; then
        _W63_LOSS_NONZERO=0; _W63_LOSS_LAST=0
        die "6.2.9.F.4 НЕИЗМЕРИМ (№294): окно подачи «${label}» — снимок границы отсутствует или пуст ($(basename "$f0") / $(basename "$f1")), потери внутри окна снять нечем; вердикт этого окна остаётся НИЖНЕЙ ОЦЕНКОЙ без числа"
        return 0
    fi
    d=$(( $(_w63_real_drops "$f1") - $(_w63_real_drops "$f0") ))
    if [ "$W63_LIB_OK" -eq 1 ] && [ "${d:-0}" -ne 0 ]; then
        w63_drops_by_reason "$f0" "$f1" | sed 's/^/    /'
    fi
    if [ "${d:-0}" -ne 0 ]; then
        _W63_LOSS_NONZERO=1
    else
        _W63_LOSS_NONZERO=0
    fi
    _W63_LOSS_LAST=${d:-0}
    pass "6.2.9.F.4 ИЗМЕРЕНО (№294, порог величине не назначается): окно подачи «${label}» — дельта потерь без path_denylist = ${_W63_LOSS_LAST}$([ "${_W63_LOSS_NONZERO}" -eq 1 ] && echo ' (ненулевая: вердикт этого окна — НИЖНЯЯ ОЦЕНКА, разбивка по {collector,reason} выше)' || echo ' (ноль напечатан обеими границами, как требует постановка)')"
}
