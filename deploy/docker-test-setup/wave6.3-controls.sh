# №320 (волна 6.2.9.F.3) — ПРЯМОЕ ЧИСЛО ЦЕНЫ ЧТЕНИЯ, А НЕ ОЦЕНКА ПО СИММЕТРИИ.
#
# Оценка выше систематически даёт НОЛЬ, и это не свойство читателя, а
# свойство способа: парные чтения идут в миллисекундах друг от друга, а
# алерты читателя приходят через ~0.4 с — во второй снимок они не успевают.
# Архив 14.09.2026 печатает «цена чтения 0» на обеих границах, и тот же архив
# содержит собственные алерты читателя: три curl'а границы открытия
# (21:55:07.202/.215/.235, дерево `bash→run-6.2.6-pipel→…→curl`) и четыре
# curl'а границы закрытия (22:05:22.385….454). Ноль был приборным.
#
# Прямое число берётся из стора ПО ДЕРЕВУ — тем же предикатом, которым item 3
# снял протечку верхней границы. Обе границы считаются одинаково: алерты
# СВОЕГО дерева в окне +2 с после отметки чтения.
# ═════════════════════════════════════════════════════════════════════════════
if [ "$_w63_read_cost_measurable" -eq 1 ]; then
    echo "  №320: цена чтения ПРЯМЫМ ЧИСЛОМ по дереву из стора — открытие ${_w63_read_cost_open} алертов в [опорный снимок, t0), закрытие ${_w63_read_cost_close} в [t1, t1+2с). Оценка по метрике выше даёт ноль по построению (алерты читателя не успевают к парному чтению) и нулём не является"
    if [ "${_w63_own_cost_start:-0}" -eq 0 ] && [ "$_w63_read_cost_open" -gt 0 ]; then
        echo "  ⚠ №320: оценка по метрике на открытии = 0 при ${_w63_read_cost_open} алертах читателя по дереву — ровно тот приборный ноль, ради которого прямое число и заведено"
    fi
else
    echo "  №320: цена чтения прямым числом НЕИЗМЕРИМА на этом прогоне (нет среза алертов окна либо предикат «своё» недоступен) — печатается только оценка по метрике, и она нижняя"
fi
# ЦЕНА ПОДГОТОВКИ ОКНА, СНЯТАЯ ПО СТОРУ (№319) — рядом с метрической, чтобы
