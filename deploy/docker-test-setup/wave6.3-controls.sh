        "$_w63_tree_q"'
        [.[]|select((w63ts >= $a) and (w63ts < ($a + 1)))|select(own)|select(.comm == "curl")]|length' \
        "$W63_ART/alerts-window-end.json" 2>/dev/null)
    _w63_ref_read_cost=${_w63_ref_read_cost:-0}
fi
_w63_ident_abs=$_w63_ident_diff
[ "$_w63_ident_abs" -lt 0 ] && _w63_ident_abs=$(( - _w63_ident_abs ))
echo "  №319 сторож границ: слой1(Δ)=${_w63_ident_metric}, стор в [опорный снимок, t1)=${_w63_ident_store}, расхождение ${_w63_ident_diff}; цена ОПОРНОГО чтения по дереву (№323) = ${_w63_ref_read_cost}"
if [ "$_w63_ident_diff" -lt 0 ] && [ "$_w63_ident_abs" -le "${_w63_ref_read_cost:-0}" ] && [ "${_w63_ref_read_cost:-0}" -gt 0 ]; then
    echo "    №323: тождество сошлось В ПРЕДЕЛАХ ЦЕНЫ ОПОРНОГО ЧТЕНИЯ — стор опережает метрику на ${_w63_ident_abs} при ${_w63_ref_read_cost} алертах самого опорного curl'а. Это не протечка границы: алерты, поднятые ЭТИМ чтением, физически не могут стоять в снимке, которым оно же и получено. Ноль здесь запрещён механикой, и требовать его — провалить прогон за исправную работу"
elif [ "$_w63_ident_diff" -ne 0 ]; then
    echo "    ⚠ №319: тождество НЕ сошлось. Разбираются ровно три причины: (а) метрическое окно шире сторового — между опорным снимком и t1 есть работа, которой стор не отдал (дефект границ, тот же класс, что №319); (б) часть алертов не доехала до стора (drain выше = ${_w63_drain:-?}с); (в) стор хранит НЕ ровно не-info ярус. Пока причина не названа, величина окна читается как ВЕРХНЯЯ оценка"
fi
echo "  построчно (rule_id: метрика | стор | разъезд). Знак разъезда осмыслен САМ ПО СЕБЕ:"
echo "    метрика > стора — ЧЕТЫРЕ причины, проверяются в этом порядке: (0) ГРАНИЦЫ окна у метрики и стора разные — до 15.09.2026 это была самая КРУПНАЯ причина и не значилась в списке вовсе (№319: опорный снимок брался за ${W63_OPEN_SETTLE}с до t0, и весь пусковой аппарат измерителя ложился в дельту — 29 из 52 разъезда на архиве 14.09.2026); сторож тождества выше проверяет это числом; (1) метрика включает работу ЧИТАТЕЛЯ — оценка = ${_w63_own_cost_end:-?} алертов по метрике, прямое число по дереву — ${_w63_read_cost_close:-?} (6.2.9.F.2/№320); (2) severity ниже store.min_severity (законно — это весь info-ярус); (3) стор всё ещё отстаёт (drain);"
echo "    стор > метрики — строка окна записана агентом ДО опорного снимка (граница снимка), находка."
printf '%s\n' "$_w63_metric_by_rule" > "$W63_ART/w63-metric-by-rule.txt"
printf '%s\n' "$_w63_store_by_rule" > "$W63_ART/w63-store-by-rule.txt"
_w63_split=$(awk '
    FILENAME == ARGV[1] && NF == 2 { m[$1] = $2; seen[$1] = 1 }
    FILENAME == ARGV[2] && NF == 2 { s[$1] = $2; seen[$1] = 1 }
    END { for (r in seen) printf "%s метрика=%d стор=%d разъезд=%+d\n", r, m[r]+0, s[r]+0, (s[r]+0) - (m[r]+0) }
