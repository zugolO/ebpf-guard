# не мог попасть в снимок, снятый раньше. Правка item 3 —
# internal/store/sqlite.go: новая колонка `process_tree`, без неё
# /api/v1/alerts всегда отдавал пустое дерево (память
# alerts-api-has-no-process-chain) и атрибуция по дереву была структурно
# недоступна. Предикат — принадлежит ли pid ЭТОГО скрипта ($$) цепочке
# ПРЕДКОВ алерта (движок уже строит её в LineageTracker на каждое событие),
# а не совпадает ли pid алерта с заранее собранным списком: он не зависит от
# МОМЕНТА порождения потомка внутри прогона.
echo "--- 6.2.9.F.3: атрибуция по дереву (№293) ---"
# ГРАНИЦА ОКНА ТОЧНАЯ, С ДРОБНОЙ ЧАСТЬЮ (`w63ts`, правка №291). Соседние
# блоки этого файла сравнивают время через `sub("\\.[0-9]+Z$";"Z")`, то есть
# усекают отметку до секунды, и `<= t1` втягивает в окно ВСЁ, что случилось в
# [t1, t1+1) — ровно те семь curl/awk/cp/sleep, которыми №295 и доказала
# протечку верхней границы. Здесь это недопустимо вдвойне: блок как раз и
# существует, чтобы отличить работу измерителя от работы ноды, и усечение
# приписало бы окну собственную работу читателя, а потом честно назвало бы её
# «измеритель» — атрибуция верная, окно неверное.
#
# ПРЕДИКАТ — ПРИНАДЛЕЖНОСТЬ $$ ЦЕПОЧКЕ, ПО pid ЛИБО ПО ppid. Одного `.pid ==
# $self` мало: LineageTracker строит цепочку из НАБЛЮДЁННЫХ exec'ов, и bash
# самого контроля стартовал ДО агента (или выпал по TTL/MaxDepth) — тогда в
# дереве останется только потомок, зато его `.ppid` по-прежнему указывает на
# $$. Сравнение по ppid не может дать ложного «своего»: чужой процесс с
# ppid == $$ есть по определению потомок этого скрипта.
_w63_self_pid=$$
# СТОРОЖ ПРЕДИКАТА (найден при реплее правки исхода А, 11.09.2026). Предикат
# «своё» включает `.ppid == $self`, и при $$ == 1 он совпадает с КАЖДЫМ корнем
# дерева — у корня ppid равен 1 по построению. Тогда вся величина окна была бы
# объявлена работой измерителя, а цена события ноды — нулём: приборный ноль,
# неотличимый от продуктового. Скрипт может оказаться PID 1 буквально (запуск
# пайплайна как единственного процесса контейнера), поэтому случай не
# гипотетический и закрывается явной неизмеримостью, а не молчанием.
_W63_TREE_SELF_OK=1
[ "${_w63_self_pid:-1}" -le 1 ] && _W63_TREE_SELF_OK=0
_w63_tree_q='def w63ts: (.timestamp | capture("^(?<i>[^.]+)(\\.(?<f>[0-9]+))?Z$")) as $c
       | ($c.i + "Z" | fromdateiso8601) + (($c.f // "0") | ("0." + .) | tonumber);
     def own: (.process_tree // []) | any(.pid == $self or .ppid == $self);'
_w63_alerts_json="$W63_ART/alerts-window-end.json"
if [ ! -s "$_w63_alerts_json" ]; then
    die "6.2.9.F.3 НЕИЗМЕРИМ (№293): среза алертов на границе закрытия окна нет или он пуст ($_w63_alerts_json) — атрибуцию считать не по чему, и ноль здесь был бы приборным"
else
_w63_window_total_n=$(jq --argjson t0 "$_w63_t0" --argjson t1 "$_w63_t1" --argjson self "$_w63_self_pid" \
    "$_w63_tree_q"' [.[]|select((w63ts >= $t0) and (w63ts <= $t1))]|length' "$_w63_alerts_json" 2>/dev/null)
_w63_tree_own_n=$(jq --argjson t0 "$_w63_t0" --argjson t1 "$_w63_t1" --argjson self "$_w63_self_pid" \
    "$_w63_tree_q"' [.[]|select((w63ts >= $t0) and (w63ts <= $t1))|select(own)]|length' "$_w63_alerts_json" 2>/dev/null)
_w63_tree_unattr_n=$(jq --argjson t0 "$_w63_t0" --argjson t1 "$_w63_t1" --argjson self "$_w63_self_pid" \
    "$_w63_tree_q"' [.[]|select((w63ts >= $t0) and (w63ts <= $t1))|select(((.process_tree // [])|length) == 0)]|length' "$_w63_alerts_json" 2>/dev/null)
# ПРЯМОЕ ЧИСЛО ПРОТЕЧКИ ВЕРХНЕЙ ГРАНИЦЫ (№295), которое item 2 снять не мог:
# алерты ПОСЛЕ t1, опознанные как свои ПО ДЕРЕВУ, а не по догадке о comm.
_w63_tree_leak_n=$(jq --argjson t1 "$_w63_t1" --argjson self "$_w63_self_pid" \
    "$_w63_tree_q"' [.[]|select((w63ts > $t1) and (w63ts <= ($t1 + 2)))|select(own)]|length' "$_w63_alerts_json" 2>/dev/null)
_w63_tree_own_n=${_w63_tree_own_n:-0}; _w63_tree_unattr_n=${_w63_tree_unattr_n:-0}
_w63_window_total_n=${_w63_window_total_n:-0}; _w63_tree_leak_n=${_w63_tree_leak_n:-0}
_w63_tree_node_n=$(( _w63_window_total_n - _w63_tree_own_n - _w63_tree_unattr_n ))
echo "  всего алертов в окне [t0,t1] (точная граница, дробная часть не усечена): ${_w63_window_total_n}"
echo "  по дереву — нода: ${_w63_tree_node_n}, измеритель: ${_w63_tree_own_n}, НЕАТРИБУТИРУЕМО (пустой process_tree): ${_w63_tree_unattr_n}"
echo "  для сверки: та же доля по СТАТИЧЕСКОМУ набору pid (вход соседнего критерия, снят ДО t0) = ${_w63_instr_own_n:-0} — расхождение с ${_w63_tree_own_n} и есть цена слепоты статического набора к потомкам, порождённым на границах окна (№293)"
echo "  протечка верхней границы (№295), снятая ПО ДЕРЕВУ, а не оценкой: ${_w63_tree_leak_n} алертов измерителя в (t1, t1+2с] — в величину окна НЕ входят и из неё не вычитаются, печатаются как размер эффекта"
if [ "$_W63_TREE_SELF_OK" -eq 0 ]; then
    die "6.2.9.F.3 НЕИЗМЕРИМ (№293): pid измерителя = ${_w63_self_pid} — предикат «своё» по ppid совпал бы с КАЖДЫМ корнем дерева (у корня ppid = 1), и вся величина окна была бы приписана работе замера. Атрибуция по дереву в этом окружении (скрипт исполняется как PID 1) недоступна, и ноль здесь был бы приборным"
elif [ "$_w63_window_total_n" -eq 0 ]; then
    die "6.2.9.F.3 НЕИЗМЕРИМ (№293): в срезе нет НИ ОДНОГО алерта с отметкой внутри [t0,t1] — либо срез снят не тем окном, либо агент молчал всё окно; атрибуция тривиальна только на вид, и ноль здесь приборный, а не вердикт"
elif [ "$_w63_tree_unattr_n" -eq "$_w63_window_total_n" ]; then
    die "6.2.9.F.3 НЕИЗМЕРИМ (№293): ни один алерт окна не несёт process_tree — либо profiler.lineage.enabled=false, либо на стенде не задеплоена правка стора (internal/store/sqlite.go: колонка process_tree; требует make build + рестарт юнита), либо LineageTracker не успел построить цепочку ни для одного pid окна; атрибуция по дереву недоступна, item 3 этим прогоном не подтверждён"
else
    pass "6.2.9.F.3 ИЗМЕРЕНО (№293, порог величине не назначается): величина окна разделена ПО ДЕРЕВУ ПРЕДКОВ (pid скрипта = ${_w63_self_pid}), а не по имени процесса — нода ${_w63_tree_node_n}, измеритель ${_w63_tree_own_n}, неатрибутируемый остаток ${_w63_tree_unattr_n} напечатан явно и входит в величину как её неизмеримая часть"
fi
fi

