else
    pass "6.2.9.F.2 ИЗМЕРЕНО (№295, порог величине не назначается): оценка цены чтения (${_w63_own_cost_end:-0}) меньше запаса гейта (${_w63_margin_abs}) — сама по себе не делает вердикт объёма тихого окна неизмеримым, но остаётся систематической нижней оценкой (не нулём) и оценкой (не измерением: перенесена со второго чтения на первое по допущению равной стоимости). Величина ТОЛЬКО печатается и нигде не вычитается из формулы (а)"
