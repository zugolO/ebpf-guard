    awk '/^ebpf_guard_alert_volume_by_source_total\{/ && /comm="k3s-server"/ && !/rule_id="k8s_kubectl_apiserver_exec"/ { s += $NF } END { printf "%d", s+0 }' "$1" 2>/dev/null
