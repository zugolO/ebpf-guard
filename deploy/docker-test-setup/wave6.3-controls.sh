       'def w63ts: (.timestamp | capture("^(?<i>[^.]+)(\\.(?<f>[0-9]+))?Z$")) as $c
          | ($c.i + "Z" | fromdateiso8601) + (($c.f // "0") | ("0." + .) | tonumber);
        [.[]|select((w63ts >= $t0) and (w63ts <= $t1))]|length' \
       "$1" 2>/dev/null || echo 0
}
