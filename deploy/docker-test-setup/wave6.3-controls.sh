echo "  6.2.6.13: ebpf_guard_events_excluded_total{reason=\"observer_tree\"} открытие=${_w63_obs0:-ОТСУТСТВУЕТ} закрытие=${_w63_obs1:-ОТСУТСТВУЕТ}"
if [ -z "${_w63_obs0:-}" ] || [ -z "${_w63_obs1:-}" ]; then
    die "6.2.6.13 НЕИЗМЕРИМ: серия observer_tree отсутствует хотя бы на одной границе окна — агент собран без пре-регистрации (item 7 правки не задеплоены), отсутствие среза дерева измерителя доказать нечем"
else
    _w63_obs_delta=$(( _w63_obs1 - _w63_obs0 ))
    if [ "$_w63_obs_delta" -gt 0 ]; then
        die "6.2.6.13 ПРОВАЛЕН: observer_tree исключил $_w63_obs_delta событий за окно — дерево измерителя резалось В ЯДРЕ, прогон НЕИЗМЕРИМ (часть величины 6.2.6.1 уехала вместе с исключением, находка №260)"
    else
        pass "6.2.6.13 ДОСТИГНУТО: observer_tree за окно = 0 — фильтр либо выключен, либо не резал ничего, и это доказано числом, а не отсутствием серии"
    fi
fi

