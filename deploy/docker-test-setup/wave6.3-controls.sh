# 6.2.9.F.2 (№295, item 2 волны 6.2.9.F) — ГЕЙТ НЕИЗМЕРИМ, ЕСЛИ ЦЕНА ЧТЕНИЯ
# СРАВНИМА С ЗАПАСОМ. Печатается ТРЕТЬЕЙ величиной подряд рядом с ценой ноды:
# 90/ч при пороге 100/ч и цене чтения 6 не есть «взят» — снимок, который сам
# добавляет к измеряемой величине, не вправе решать, взят ли гейт, если его
# собственная добавка сопоставима с оставшимся запасом до порога.
#
# ЧТО ЗДЕСЬ ИМЕННО СРАВНИВАЕТСЯ. `_w63_own_cost_end` — цена ВТОРОГО чтения
# (см. комментарий у его вычисления выше), перенесённая на ПЕРВОЕ (штатное)
# чтение по допущению, что оба чтения стоят одинаково. Это ОЦЕНКА, не
# измерение первого чтения впрямую — измерить его нечем, кроме как ещё одним
# чтением, которое стоит ту же цену. Отсюда критерий сравнивает НЕИЗМЕРИМОСТЬ
# по оценке, а не по факту, и остаётся строго ПЕЧАТЬЮ величины: она нигде не
# вычитается из формулы (а) (см. `_w63_vol`/`_w63_vol_hour` — оба считаются
# только по дельте штатных снимков, без участия `_w63_own_cost_*`), и не
# войдёт в неё, пока item 3 (атрибуция по дереву) не даст способ отличить
# алерты измерителя от алертов ноды напрямую, а не оценкой по симметрии.
# ═════════════════════════════════════════════════════════════════════════════
echo "--- 6.2.9.F.2: цена чтения против запаса гейта (№295) ---"
