# ЕДИНСТВЕННОГО рестарта прогона — рестарта агента на Шаге 1 — переехал в
# run-6.3-pipeline.sh, где он заменил слепой `sleep 30`.
#
# №337: барьер готовности после ЛЮБОГО рестарта агента внутри прогона.
# $1 = эпоха ДО рестарта (секунды). Ждёт /health И
# process_start_time_seconds > $1 — обе стороны нужны, потому что /health
# отвечает раньше, чем экспортёр публикует свежий process_start_time
# (гонка, которой посвящена wave6.3.1 item 4), а голый process_start_time
# без /health читал бы старый снимок как новый на медленно поднимающемся
# сервере. Падает С НАЗВАННОЙ ПРИЧИНОЙ и не прерывает прогон.
_w63_wait_ready() {
    _w63_pre_epoch="$1"
    _w63_rtries="${W63_READY_TRIES:-20}"
    _w63_rwait="${W63_READY_WAIT:-3}"
    _w63_rn=1
    while [ "$_w63_rn" -le "$_w63_rtries" ]; do
        _w63_r_health=$(_w63_curl -o /dev/null -w '%{http_code}' "$W63_API/health" 2>/dev/null)
        if [ "$_w63_r_health" = "200" ]; then
            _w63_r_pst=$(_w63_curl "$W63_API/metrics" 2>/dev/null | awk '$1=="process_start_time_seconds"{print $2; exit}')
            if [ -n "${_w63_r_pst:-}" ] && awk -v a="$_w63_r_pst" -v b="$_w63_pre_epoch" 'BEGIN{exit !(a>b)}'; then
                echo "  барьер готовности: агент поднят (process_start_time_seconds=${_w63_r_pst} > ${_w63_pre_epoch}), попытка ${_w63_rn}/${_w63_rtries}"
                return 0
            fi
        fi
        sleep "$_w63_rwait"
        _w63_rn=$(( _w63_rn + 1 ))
    done
    die "БАРЬЕР ГОТОВНОСТИ НЕ ПРОЙДЕН (№337): после рестарта $W63_API/health и/или process_start_time_seconds не подтвердили новый агент за $(( _w63_rtries * _w63_rwait ))с — все снимки метрик, взятые после этой точки, недействительны до ручной проверки"
    return 1
}

# №337: инвариант — любая дельта двух снимков метрик обязана сверить их
# process_start_time_seconds. Расхождение значит, что между снимками агент
# перезапускался и счётчики обнулились: дельта в этом случае не число, а
# НЕИЗМЕРИМО (сравнение до/после рестарта бессмысленно в любом знаке).
# $1=файл_A $2=файл_B — печатает "ok" или "restarted:PST_A:PST_B" в stdout.
_w63_pst_of() { awk '$1=="process_start_time_seconds"{print $2; exit}' "$1" 2>/dev/null; }
_w63_delta_guard() {
    _w63_dg_a=$(_w63_pst_of "$1")
    _w63_dg_b=$(_w63_pst_of "$2")
    if [ -z "${_w63_dg_a:-}" ] || [ -z "${_w63_dg_b:-}" ]; then
        echo "unknown"
        return 1
    fi
    if [ "$_w63_dg_a" != "$_w63_dg_b" ]; then
        echo "restarted:${_w63_dg_a}:${_w63_dg_b}"
        return 1
    fi
    echo "ok"
    return 0
}
# ЭПОХА — ВСТРОЕННЫМ printf, а не `date`. Каждый вызов внешнего `date` —
# это execve, а значит собственное событие измерителя: на прогоне 06.09.2026
# критерий 6.2.6.3 упал ровно на двух алертах comm=date, которые породил сам
# контроль строкой «окно открыто …» СРАЗУ ПОСЛЕ фиксации t0. Встроенный
# printf процесса не создаёт вовсе, поэтому источник исчезает, а не сдвигается.
# TZ=UTC экспортирован выше — форматы ниже эквивалентны `date -u`.
_w63_epoch() { local _e; printf -v _e '%(%s)T' -1; printf '%s' "$_e"; }
# №324 (волна 6.2.9.F.3, разбор 15.09.2026) — ДРОБНАЯ отметка для пары границ
# подготовки окна. `%(%s)T` даёт ЦЕЛУЮ секунду, а весь пусковой аппарат замера
# отрабатывает за ~170 мс: на боевом прогоне 15.09.2026 обе отметки совпали
# (t_presettle = t_baseline = 1789465465), интервал «цена подготовки по стору»
# получил нулевую ширину и напечатал 0 при 30 стоявших там алертах, из них 23
# деревом измерителя. Это ровно №291 ([[store-window-jq-truncates-to-second]]),
# не перенесённый в новую пару границ. В bash-арифметику эти две отметки не
# входят НИ РАЗУ (проверено: только jq --argjson и printf), поэтому дробность
# здесь безопасна; t0/t1 остаются целыми — на них считают длину окна.
_w63_epoch_f() {
    local _e
    _e=$(date -u +%s.%N 2>/dev/null) || _e=""
    case "$_e" in
        *[!0-9.]*|"") _w63_epoch ;;   # date без %N (busybox) — честно падаем на целую
        *) printf '%s' "$_e" ;;
    esac
}
_w63_utc() { printf '%(%Y-%m-%dT%H:%M:%SZ)T' "$1"; }

# Сумма метрики по срезу. Прямая дельта двух срезов, а не строка таблицы:
# строка индексирована срезом лимитера (память f6b-table-indexed-by-limiter-cut).
_w63_metric_sum() { # $1=metric $2=список label-значений (rule_id ИЛИ comm; пусто = все) [$3=файл среза]
    # №267 (item 5): фильтр match'ит значение ЛЮБОГО лейбла в кавычках, а не
    # только rule_id="..." — иначе _w63_metric_sum не может выделить comm
    # для метрик без rule_id (ebpf_guard_drift_baseline_signature_cap_reached_total{comm=...}),
    # и вызывающая сторона (6.2.6.11) вынуждена звать её с пустым аргументом,
    # суммируя ВСЕ comm сразу. Возможность фильтровать уже была — не хватало
    # generic-совпадения по значению.
    # Само совпадение живёт в wave6.2.6-metrics-lib.sh (w63_metric_sum_file):
    # у библиотеки есть офлайн-сторож, который зовёт ИМЕННО ЭТУ функцию, а не
    # свою копию awk. Здесь остаётся только источник среза — живой /metrics
    # или файл. Откат на локальный awk — на случай, если библиотека не
    # подключилась (её отсутствие уже объявлено НЕИЗМЕРИМОСТЬЮ выше, но
    # молча падать на «команда не найдена» контроль не должен).
    local metric="$1" ids="${2:-}" src="${3:-}"
    if [ "$W63_LIB_OK" -eq 1 ]; then
        { [ -n "$src" ] && cat "$src" || _w63_metrics; } | w63_metric_sum_file "$metric" "$ids" -
    else
        # Откат на локальную копию: отсутствие библиотеки уже объявлено
        # НЕИЗМЕРИМОСТЬЮ выше, но контроль не должен падать «команда не
        # найдена» посреди измерения.
        { [ -n "$src" ] && cat "$src" || _w63_metrics; } | awk -v m="$metric" -v ids="$ids" '
            BEGIN { n = split(ids, a, " ") }
            $0 ~ "^"m"[{ ]" {
                if (n == 0) { s += $NF; next }
                for (i = 1; i <= n; i++) if (index($0, "\"" a[i] "\"")) { s += $NF; next }
            }
            END { printf "%d", s+0 }'
    fi
}
# Скалярная метрика без лейблов (process_*, go_*): $NF может быть в
# экспоненциальной записи (1.37413104e+08), поэтому печатается через %.0f.
_w63_metric_raw() { # $1=metric $2=файл среза
    awk -v m="$1" '$1 == m { printf "%.0f", $2+0; found=1; exit } END { if (!found) printf "" }' "$2" 2>/dev/null
}

