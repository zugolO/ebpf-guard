#
# КАК ИЗМЕРЯЕТСЯ. `drain` подбирается ЭМПИРИЧЕСКИ, а не назначается: снимки
# повторяются с шагом W63_DRAIN_STEP, пока число строк В ГРАНИЦАХ [t0,t1]
# не перестанет расти два раза подряд. Назначить его числом заранее значило
# бы угадать ровно ту величину, ради которой этот критерий и существует.
#
# ПОЧЕМУ СНИМОК ПОСЛЕ СЛИВА СТАНОВИТСЯ ОСНОВНЫМ. Все сторовые контроли
# фильтруют по [t0,t1] сами, поэтому более поздний снимок для них — строгое
# надмножество: он не добавляет ничего вне окна, а внутри окна добавляет то,
# что раньше терялось. Снимок ровно на t1 сохраняется отдельным файлом —
# без него разъезд нечем было бы предъявить.
#
# ПОРОГ НЕ НАЗНАЧАЕТСЯ (5.9.6). Невозможность назвать drain = НЕИЗМЕРИМ.
# ═════════════════════════════════════════════════════════════════════════════
echo "--- 6.2.6.19: разъезд метрики и стора, drain подбирается снимками (№281) ---"
W63_DRAIN_STEP="${W63_DRAIN_STEP:-$([ "$W63_SMOKE" = "1" ] && echo 5 || echo 10)}"
W63_DRAIN_MAX="${W63_DRAIN_MAX:-$([ "$W63_SMOKE" = "1" ] && echo 20 || echo 60)}"
# НАЙДЕНО №293 (разбор архива collect-6.2.6, 10.09.2026): `sub(...)|
# fromdateiso8601` отрезал дробную часть ДО парсинга, поэтому весь
# промежуток [t1.000, t1.999] читался как «= t1» и проходил `<= t1`.
# На архиве это дало ложное drain=10с — 6 строк, которые «доехали после
# слива», были на деле собственными алертами КОНТРОЛЯ на t1+0,16…0,25с
# (curl/cp/cut/jq читают метрики контроля сразу после открытия окна) и
# были В ОКНЕ уже на снимке РОВНО на t1 при точном сравнении. `w63ts`
# сохраняет дробную часть как float-эпоху, так что `<= $t1` (целое)
# отбрасывает всё, что позже t1 хоть на миллисекунду.
_w63_store_in_window() { # $1=файл снимка стора → число строк в границах [t0,t1]
