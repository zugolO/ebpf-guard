    echo "  №319: цена подготовки окна по СТОРУ (между снимком до осадки и опорным): всего ${_w63_settle_stored:-0}, из них дерева измерителя ${_w63_settle_stored_own:-0}; по МЕТРИКЕ (с info-ярусом) ${_W63_SETTLE_VOL:-?}. До 15.09.2026 эта величина целиком лежала в величине окна"
