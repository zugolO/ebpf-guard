# Условие 3 (item 7, №312): пайплайн не вправе печатать «находок класса
# «измеритель» — ноль» ДО разбора. Он печатает то единственное, что знает, —
# список меток, провалившихся на ЭТОМ прогоне, и явную оговорку, что реестр
# судит вердикты пайплайна, а не разбор архива.
# ---------------------------------------------------------------------------
# №317 (смок 14.09.2026, 21:01Z). ИНТЕРАКТИВНЫЙ ВХОД ОПЕРАТОРА В ОКНО —
# ЗАГРЯЗНЕНИЕ, КОТОРОЕ ПРЕДИКАТ «СВОЁ» НЕ ЛОВИТ ПО ПОСТРОЕНИЮ.
#
# Смок: окно [21:01:15, 21:02:15], проверка запуска ssh'ем в 21:01:33. Дерево
# этой сессии (`sshd → sh → run-parts → 00-header → uname`) стало САМЫМ
# ДОРОГИМ деревом окна (15 алертов, победитель цены) и ОНО ЖЕ провалило
# 6.2.4.6 — то есть обе величины, ради которых волна и ставится, оказались
# ценой захода измерителя. Предикат «своё» его не видит: дерево висит на
# `sshd`/systemd, а не на пайплайне, — ровно как у механизма введения события
# (№302) и как в памяти gate-value-can-be-entirely-measurer.
#
# Сторож не чинит загрязнение (чинит его дисциплина: не заходить на стенд от
# постановки таймера до конца окна) — он делает его НАЗВАННЫМ. Молчаливое
# загрязнение неотличимо от свойства ноды, и вердикт по такому окну читается
# сильнее, чем измерен.
#
# Считает принятые аутентификации ssh внутри [t0,t1] по тексту журнала.
# Разбор отделён от самого journalctl нарочно — так он проверяется офлайн на
# фикстуре (память self-test-fixtures-miss-live-log-shape).
# ---------------------------------------------------------------------------
w63_ssh_logins_in_window() { # $1=t0 (эпоха) $2=t1 (эпоха) $3=файл журнала ssh ("-"=stdin), строки с «Accepted …»
    local t0="${1:-0}" t1="${2:-0}" src="${3:--}"
    awk -v t0="$t0" -v t1="$t1" '
        /Accepted (publickey|password|keyboard-interactive)/ {
            # journalctl --output=short-unix печатает эпоху первым полем
            ts = $1 + 0
            if (ts >= t0 && ts <= t1) n++
        }
        END { print n + 0 }
    ' "$src"
}

