# реестр строкой «6.2.6.1 OK». Условие 1 критерия 6.2.6.21 читает реестр
# буквально — и при ПРОВАЛЕННОМ гейте нашло бы OK подпункта, объявив условие
# взятым. Подпункт теперь получает ключ «<метка>/подпункт».
#
# ПОЧЕМУ МЕТКА БЕРЁТСЯ ТОЛЬКО ИЗ НАЧАЛА СТРОКИ (правка волны 6.2.9.F,
# 11.09.2026). Прежняя форма искала ПЕРВОЕ вхождение `6.2.[123456].X` где
# угодно в тексте, и это давало ровно тот же класс ложного PASS, ради
# которого ключ и заводился, только на шаг раньше: вердикт нового критерия
# `6.2.9.F.2` ссылается в своём тексте на гейт («…не делает вердикт 6.2.6.1
# неизмеримым»), и его OK/FAIL писался в реестр под ключом ЧУЖОЙ метки —
# `6.2.6.1 FAIL` от критерия, который про гейт ничего не решает. Условие 1
# критерия 6.2.6.21 прочитало бы гейт проваленным при взятом гейте.
# Инвариант, на который опирается якорь, проверен по всем call-site'ам
# die()/pass() в wave6.2.6-controls.sh: КАЖДЫЙ текст вердикта начинается со
# своей метки (ни одного исключения), поэтому «первое вхождение где угодно»
# не давало ничего сверх якоря, зато ловило чужие ссылки. Заодно снято
# ограничение `[123456]` на третий сегмент — метки волны 6.2.9.F в реестр не
# попадали вовсе (пустой ключ = молчаливый пропуск, тот же №269).
# ---------------------------------------------------------------------------
w63_label_key() { # $1=текст вердикта → ключ реестра ("" если метки в тексте нет
    local lbl
    lbl=$(printf '%s' "$1" | grep -oE '^6\.[0-9]+(\.[A-Za-z0-9]+)*' | head -1)
    [ -n "${lbl:-}" ] || return 0
    # ТОЛЬКО «подпункт». Слово «половина» намеренно НЕ перехватывается: у
    # 6.2.4.5/6.2.6.22 ГЛАВНЫЙ вердикт сам звучит как «половины: …», и
    # переименование ключа по нему увело бы из реестра главную метку.
    case "$1" in
        *подпункт*) printf '%s/подпункт' "$lbl" ;;
        *)          printf '%s' "$lbl" ;;
    esac
}

# Метка ВЗЯТА, только если у неё есть строка OK и НЕТ строки FAIL. Одного
# grep'а по OK мало: метка может вынести оба вердикта (контроль исполнился
# дважды, ветка die сработала после pass) — тогда взятой она не является.
w63_label_taken() { # $1=метка $2=файл реестра
    local esc="${1//./\\.}"
    grep -qE "^${esc} OK$" "${2:-/dev/null}" 2>/dev/null || return 1
    grep -qE "^${esc} FAIL$" "${2:-/dev/null}" 2>/dev/null && return 1
    return 0
}

