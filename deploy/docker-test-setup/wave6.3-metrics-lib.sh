# ИНВАРИАНТЫ АРХИВА (волна 6.2.9.F.3, 15.09.2026).
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ `--self-test`. Тот проверяет ФИКСТУРЫ: умеет ли разбор
# прочитать синтетический вход. За кустом 6.2.x он ни разу не нашёл находки —
# и был зелёным на архиве `collect-6.2.9.F.2`, который несёт №319, №320 и
# №321 одновременно. Находят не фикстуры, а ИНВАРИАНТЫ на РЕАЛЬНЫХ архивах:
# свойства, которые обязаны выполняться на каждом когда-либо собранном
# архиве. Нарушенный инвариант есть находка по определению.
#
# ОБЩАЯ ФОРМА ВСЕХ ПЯТИ: каждое напечатанное вердиктом число обязано
# пересчитываться из артефактов НЕЗАВИСИМЫМ путём; расхождение — находка.
# Так найдены все четыре находки 15.09.2026, и ни одна из них не потребовала
# ни минуты стенда ([[gate-offline-replay-on-mac]]).
#
# ПРЕДИКАТ «СВОЁ» ОФЛАЙН. Живой контроль знает `$$`; архив — нет, зато несёт
# `measurer-pids.txt` (цепочка предков пайплайна + его потомки на момент
# снятия). Здесь «своё» = ЛЮБОЙ элемент `process_tree` алерта лежит в этом
# наборе. Это сильнее живого статического предиката (№293), который
# сравнивал только `.pid` листа: корень дерева в наборе есть всегда.
#
# ОТСУТСТВИЕ СТРОКИ В ЛОГЕ — НЕ ПРОВАЛ, А «НЕПРИМЕНИМ», И ЭТО ПЕЧАТАЕТСЯ
# СЛОВОМ (память verdict-zero-needs-its-class-presented): старые архивы
# собраны пайплайном без блока 6.2.9.F.3, и молчаливый ноль читался бы как
# сошедшийся инвариант. Лог читается ТОЛЬКО `grep -a` — часть архивов
# невалидна в UTF-8 (№309, память archive-log-invalid-utf8-blinds-grep).
# ═══════════════════════════════════════════════════════════════════════════
W63_INV_SETTLE="${W63_INV_SETTLE:-20}"

_W63_INV_JQ='def w63ts: (.timestamp | capture("^(?<i>[^.]+)(\\.(?<f>[0-9]+))?Z$")) as $c
       | ($c.i + "Z" | fromdateiso8601) + (($c.f // "0") | ("0." + .) | tonumber);
     def trunc_ts: (.timestamp | sub("\\.[0-9]+Z$";"Z") | fromdateiso8601? // 0);
     def own: (.process_tree // []) | any(.pid as $p | ($pids | index($p)) != null);'

_w63_inv_say() { # $1=номер $2=вердикт $3=текст
    printf '    %-3s %-11s %s\n' "$1" "$2" "$3"
}

w63_archive_invariants() { # $1=каталог архива → 0 если ни один инвариант не нарушен
    local a="${1:?каталог архива}"
    local art="$a/controls/artifacts"
    local we="$art/window-epoch.txt"
    local al="$art/alerts-window-end.json"
    local ms="$art/metrics-window-start.txt" me="$art/metrics-window-end.txt"
    local pf="$art/measurer-pids.txt"
    local log; log=$(ls "$a"/run-*.log 2>/dev/null | head -1 || true)
    local rc=0 legacy=0

    for f in "$we" "$al" "$ms" "$me"; do
        [ -s "$f" ] || { echo "    НЕПРИГОДЕН к реплею: нет $f"; return 2; }
    done

    local t0 t1
    # Каждая подстановка ниже закрыта `|| true`: библиотека исполняется под
    # `set -e`/`pipefail`, и `grep` без совпадения — законный исход разбора
    # старого архива, а не ошибка ([[sourcing-lib-leaks-set-e]]). Без этого
    # сторож умирал молча на первом же архиве без нужной строки.
    t0=$(grep -a '^t0=' "$we" 2>/dev/null | cut -d= -f2 || true)
    t1=$(grep -a '^t1=' "$we" 2>/dev/null | cut -d= -f2 || true)
    [ -n "${t0:-}" ] && [ -n "${t1:-}" ] || { echo "    НЕПРИГОДЕН: границы окна не прочитаны из $we"; return 2; }

    local pids='[]'
    [ -s "$pf" ] && pids=$(awk '{printf "%s%s", (NR>1?",":"["), $1} END{printf "%s\n", (NR?"]":"[]")}' "$pf" || true)
    [ -n "${pids:-}" ] || pids='[]'

    # ---- И1: границы окна у метрики и стора считают ОДИН промежуток (№319) ----
    #
    # ОПОРНАЯ ТОЧКА БЕРЁТСЯ ИЗ АРХИВА, А НЕ УГАДЫВАЕТСЯ. Пайплайн с 15.09.2026
    # кладёт `t_baseline` рядом с `t0`; на архивах старше её нет, и ширина
    # осадки берётся константой W63_INV_SETTLE — тогда инвариант читается
    # как «архив собран прибором с непочиненной нижней границей», и это
    # ПЕЧАТАЕТСЯ словом, а не выдаётся за свежую находку.
    #
    # ПОСЛЕ ПОЧИНКИ осадка не обязана быть нулём: опорное чтение стоит своих
    # алертов, и они приходят уже после снимка. Инвариант требует не нуля, а
    # ОБЪЯСНИМОСТИ — всё, что попало в осадку, обязано быть работой самого
    # замера (предикат «своё»). Чужой алерт в осадке = работа ноды, попавшая
    # в метрическую дельту мимо окна, то есть та же №319 в малом.
    local layer1 in_win settle settle_own diff t_base base_known ref_read
    layer1=$(( $(w63_metric_sum_file ebpf_guard_alerts_total "" "$me") \
             - $(w63_metric_sum_file ebpf_guard_alerts_total "" "$ms") ))
    in_win=$(jq --argjson t0 "$t0" --argjson t1 "$t1" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $t0) and (w63ts < $t1))]|length' "$al" 2>/dev/null || true)
    in_win=${in_win:-0}
    t_base=$(grep -a '^t_baseline=' "$we" 2>/dev/null | cut -d= -f2 || true)
    base_known=1
    case "${t_base:-}" in
        # №324: с 15.09.2026 отметка ДРОБНАЯ (1789465465.523…) — целочисленный
        # тест `-le 0` на ней срывается, и архив нового прибора читался бы как
        # архив без опорной точки, то есть УНАСЛЕДОВАННЫМ. Проверяем формой.
        [0-9]*.[0-9]*|[0-9]*) : ;;
        *) t_base="" ;;
    esac
    if [ -z "${t_base:-}" ] || [ "${t_base%%.*}" -le 0 ] 2>/dev/null; then
        base_known=0
        t_base=$(( t0 - W63_INV_SETTLE ))
    fi
    settle=$(jq --argjson a "$t_base" --argjson t0 "$t0" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $a) and (w63ts < $t0))]|length' "$al" 2>/dev/null || true)
    settle_own=$(jq --argjson a "$t_base" --argjson t0 "$t0" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $a) and (w63ts < $t0))|select(own)]|length' "$al" 2>/dev/null || true)
    settle=${settle:-0}; settle_own=${settle_own:-0}
    # Цена ОПОРНОГО чтения по дереву (№323) — та же ось, что у И4: собственные
    # алерты `curl`'а в первую секунду после опорной отметки.
    ref_read=$(jq --argjson a "$t_base" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $a) and (w63ts < ($a + 1)))|select(own)|select(.comm == "curl")]|length' "$al" 2>/dev/null || true)
    ref_read=${ref_read:-0}
    diff=$(( layer1 - in_win - settle ))
    if [ "$diff" -ne 0 ] && [ "$base_known" -eq 0 ]; then
        # Опорная точка УГАДАНА константой, и остаток обоих знаков объясняется
        # самой догадкой: осадка шире настоящей (остаток < 0) или уже неё
        # (остаток > 0). Объявлять это свежей находкой значило бы судить архив
        # по ширине, которой в нём не записано, — тот же класс, что судить
        # вердикт по метке ([[verdict-class-must-come-from-content-not-label]]).
        _w63_inv_say И1 УНАСЛЕДОВАНО "тождество не проверяемо: опорной точки в архиве нет, ширина осадки угадана t0−${W63_INV_SETTLE}с — слой1=${layer1}, окно ${in_win}, осадка ${settle}, остаток ${diff}"
        legacy=1
    elif [ "$diff" -lt 0 ] && [ "$(( - diff ))" -le "${ref_read:-0}" ] && [ "${ref_read:-0}" -gt 0 ]; then
        # №323: остаток отрицателен ровно на цену ОПОРНОГО чтения. Алерты,
        # поднятые тем самым curl'ом, которым получен опорный снимок, стоят в
        # сторовом интервале, но в этом снимке их нет и быть не может. Ноль
        # здесь запрещён механикой прибора, и требовать его — объявлять
        # находкой исправную работу.
        _w63_inv_say И1 ОК "границы сошлись В ПРЕДЕЛАХ ЦЕНЫ ОПОРНОГО ЧТЕНИЯ (№323): слой1=${layer1}, окно ${in_win}, осадка ${settle}, остаток ${diff} при ${ref_read} алертах самого опорного curl'а"
    elif [ "$diff" -ne 0 ]; then
        _w63_inv_say И1 НАХОДКА "тождество границ НЕ сошлось: слой1=${layer1}, окно ${in_win}, осадка ${settle} (опорная точка из архива), необъяснённый остаток ${diff} при цене опорного чтения ${ref_read:-0} (№323)"
        rc=1
    elif [ "$base_known" -eq 0 ] && [ "$settle" -gt 0 ]; then
        _w63_inv_say И1 УНАСЛЕДОВАНО "№319: слой1=${layer1} = окно ${in_win} + ОСАДКА ${settle} — архив собран прибором с непочиненной нижней границей (доля замера в величине $(awk -v s="$settle" -v l="$layer1" 'BEGIN{printf "%.0f%%", (l?100.0*s/l:0)}')). Пересобрать нечем, величины этого архива читать ВЕРХНИМИ оценками"
        legacy=1
    elif [ "$settle" -eq 0 ]; then
        _w63_inv_say И1 ОК "границы сошлись, осадка пуста: слой1=${layer1} = окно ${in_win}"
    elif [ "$settle_own" -eq "$settle" ]; then
        _w63_inv_say И1 ОК "границы сошлись; осадка ${settle} — ВСЯ работа самого замера (цена опорного чтения), чужого в ней нет"
    else
        _w63_inv_say И1 НАХОДКА "№319 в малом: осадка ${settle}, из них деревом замера только ${settle_own} — $(( settle - settle_own )) чужих алертов попали в метрическую дельту мимо окна"
        rc=1
    fi

    # ---- И2: внутри окна измеритель не работал, ПО ДЕРЕВУ (№321) ----
    local own_win
    own_win=$(jq --argjson t0 "$t0" --argjson t1 "$t1" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $t0) and (w63ts < $t1))|select(own)]|length' "$al" 2>/dev/null || true)
    own_win=${own_win:-0}
    if [ "$pids" = "[]" ]; then
        _w63_inv_say И2 НЕПРИМЕНИМ "measurer-pids.txt в архиве нет — предикат «своё» офлайн недоступен, и ноль здесь был бы приборным"
    elif [ "$own_win" -eq 0 ]; then
        _w63_inv_say И2 ОК "внутри [t0,t1) алертов дерева измерителя 0"
    else
        _w63_inv_say И2 НАХОДКА "внутри окна ${own_win} алертов ДЕРЕВА измерителя — величина окна содержит работу замера"
        rc=1
    fi

    # ---- И3: старая (усечённая) граница втягивала алерты из [t1, t1+1) (№291/№321) ----
    local n_trunc n_exact
    n_trunc=$(jq --argjson t0 "$t0" --argjson t1 "$t1" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((trunc_ts >= $t0) and (trunc_ts <= $t1))]|length' "$al" 2>/dev/null || true)
    n_exact=$in_win
    n_trunc=${n_trunc:-0}
    # НАХОДКОЙ считается не САМО расхождение (алерты сразу после t1 есть почти
    # всегда — это цена чтения), а ДОКАЗАННОЕ использование усечённой границы:
    # напечатанная контролем величина окна совпала с усечённой, а не с точной.
    # Иначе инвариант был бы вечно красным и его отключили бы первым заходом.
    local printed_w3=""
    [ -n "${log:-}" ] && printed_w3=$(grep -ao 'алертов от comm измерителя внутри \[t0,t1[])][^:]*: [0-9]*' "$log" 2>/dev/null | head -1 | grep -ao ': [0-9]*$' | tr -dc '0-9' || true)
    if [ "$n_trunc" -eq "$n_exact" ]; then
        _w63_inv_say И3 ОК "усечение отметки до секунды окно не меняет (${n_exact})"
    elif [ "${printed_w3:-}" = "$n_trunc" ] && [ "$n_trunc" != "$n_exact" ] && [ "$base_known" -eq 0 ]; then
        _w63_inv_say И3 УНАСЛЕДОВАНО "№291/№321: контроль напечатал ${printed_w3} — это УСЕЧЁННАЯ граница (точная даёт ${n_exact}); архив собран до правки границы 6.2.6.3"
        legacy=1
    elif [ "${printed_w3:-}" = "$n_trunc" ] && [ "$n_trunc" != "$n_exact" ]; then
        _w63_inv_say И3 НАХОДКА "№291/№321: контроль напечатал ${printed_w3} — это УСЕЧЁННАЯ граница (точная даёт ${n_exact}); $(( n_trunc - n_exact )) алертов вне [t0,t1) сосчитаны внутри окна"
        rc=1
    else
        _w63_inv_say И3 СПРАВОЧНО "усечённая граница дала бы ${n_trunc} против точной ${n_exact} — $(( n_trunc - n_exact )) алертов сразу после t1 (цена чтения); ни один контроль этого архива усечением не считал"
    fi

    # ---- И4: напечатанная цена чтения == пересчитанной по дереву (№320) ----
    local leak printed
    leak=$(jq --argjson t1 "$t1" --argjson pids "$pids" \
        "$_W63_INV_JQ"' [.[]|select((w63ts >= $t1) and (w63ts < ($t1 + 2)))|select(own)]|length' "$al" 2>/dev/null || true)
    leak=${leak:-0}
    printed=""
    # №325 (разбор боевого прогона 15.09.2026) — ЯКОРЬ ЧИТАЛ НЕ ТУ СТРОКУ.
    # `закрытие=[0-9]*` совпадает со строкой ОЦЕНКИ ПО МЕТРИКЕ («закрытие=0»),
    # про которую сам же блок 6.2.9.F.2 пишет, что она даёт ноль ПО ПОСТРОЕНИЮ
    # и нулём не является. Строка, которую item 3 волны и завёл, печатает
    # «закрытие 6» — БЕЗ знака равенства — и под старый якорь не шла вовсе.
    # Инвариант объявлял НАХОДКУ ровно там, где починка работает (6 = 6):
    # тот же класс, что [[metric-label-added-breaks-awk-anchors]] — молчаливо
    # разошедшийся якорь. Прямое число ищется ПЕРВЫМ, оценка — только запасным
    # вариантом для архивов, где прямой строки ещё нет.
    if [ -n "${log:-}" ]; then
        printed=$(grep -ao 'ПРЯМЫМ ЧИСЛОМ[^.]*закрытие [0-9]*' "$log" 2>/dev/null | head -1 \
                  | grep -ao 'закрытие [0-9]*$' | tr -dc '0-9' || true)
        [ -n "${printed:-}" ] || printed=$(grep -ao 'цена чтения[^;]*закрытие=[0-9]*' "$log" 2>/dev/null \
                  | head -1 | grep -ao 'закрытие=[0-9]*' | cut -d= -f2 || true)
    fi
    if [ "$pids" = "[]" ]; then
        _w63_inv_say И4 НЕПРИМЕНИМ "предикат «своё» офлайн недоступен (нет measurer-pids.txt)"
    elif [ -z "${printed:-}" ]; then
        _w63_inv_say И4 НЕПРИМЕНИМ "строки «цена чтения … закрытие=N» в логе нет (архив старше блока 6.2.9.F.2); пересчёт по дереву даёт ${leak}"
    elif [ "$printed" -eq "$leak" ]; then
        _w63_inv_say И4 ОК "цена чтения напечатана ${printed} и пересчитывается ${leak}"
    elif [ "$base_known" -eq 0 ]; then
        _w63_inv_say И4 УНАСЛЕДОВАНО "№320: напечатано «закрытие=${printed}», пересчёт по дереву даёт ${leak} — архив собран до правки прямого счёта"
        legacy=1
    else
        _w63_inv_say И4 НАХОДКА "№320: напечатано «закрытие=${printed}», пересчёт по дереву даёт ${leak} алертов читателя в [t1,t1+2с) — напечатанное число не пересчитывается"
        rc=1
    fi

    # ---- И5: напечатанная величина окна == пересчитанной (общая форма) ----
    local printed_win
    printed_win=""
    [ -n "${log:-}" ] && printed_win=$(grep -ao 'всего алертов в окне \[t0,t1\][^:]*: [0-9]*' "$log" 2>/dev/null | head -1 | grep -ao ': [0-9]*$' | tr -dc '0-9' || true)
    if [ -z "${printed_win:-}" ]; then
        _w63_inv_say И5 НЕПРИМЕНИМ "строки «всего алертов в окне» в логе нет (архив старше блока 6.2.9.F.3); пересчёт даёт ${in_win}"
    elif [ "$printed_win" -eq "$in_win" ]; then
        _w63_inv_say И5 ОК "величина окна напечатана ${printed_win} и пересчитывается ${in_win}"
    else
        _w63_inv_say И5 НАХОДКА "величина окна напечатана ${printed_win}, пересчёт даёт ${in_win} — вердикт и артефакты расходятся"
        rc=1
    fi

    # КОД ВОЗВРАТА РАЗЛИЧАЕТ ТРИ ИСХОДА, а не два: 0 — всё сошлось; 1 — свежая
    # находка на архиве, собранном ПОЧИНЕННЫМ прибором; 3 — нарушение, которое
    # принадлежит уже собранному архиву и пересобрать его нечем. Без третьего
