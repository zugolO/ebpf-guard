            echo "  OK: архив «${base}» снят ДО item 3 (лейбла field в метрике нет) и распознан как «лейбла нет» — контроль обязан объявить 6.2.6.15 НЕИЗМЕРИМЫМ, а не прочитать нули"
        else
            echo "  ПРОВАЛ: архив «${base}» несёт метрику БЕЗ лейбла field, а разбор этого не сказал: $axes_arch"; rc=1
        fi
    else
        if printf '%s' "$axes_arch" | grep -q 'field=НЕТ_ЛЕЙБЛА'; then
            echo "  ПРОВАЛ: архив «${base}» несёт лейбл field в метрике, а разбор вернул НЕТ_ЛЕЙБЛА — разбор оси сломан либо метрика переименована"; rc=1
        else
            echo "  OK: архив «${base}» снят ПОСЛЕ item 3 — оси разобраны поимённо, НЕТ_ЛЕЙБЛА не встречается"
        fi
    fi
    # Вердикт синтетической части возвращается КОДОМ ВОЗВРАТА, а не stdout:
    # функция печатает отчёт, и $( ) съел бы его целиком, подставив весь
    # отчёт в rc (арифметика молча получила бы мусор).
    w63_synthetic_axes_test || rc=1

    [ "$rc" -eq 0 ] && echo "СТОРОЖ ПРОЙДЕН ($base)" || echo "СТОРОЖ ПРОВАЛЕН ($base)"
    return "$rc"
}

