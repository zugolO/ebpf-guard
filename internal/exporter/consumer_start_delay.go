package exporter

// ConsumerStartDelayUnset — величина серии ebpf_guard_consumer_start_delay_seconds
// до того, как `main` её выставит (находка №473).
//
// ЗАЧЕМ ОТРИЦАТЕЛЬНОЕ ЧИСЛО. После починки порядка старта здоровая величина —
// доли миллисекунды, то есть НОЛЬ на глаз читателя и в awk-разрезе. Если бы
// серия по умолчанию несла 0, «измерено и вышло ~0» стало бы неотличимо от
// «никто не выставлял» — ровно тот класс, из-за которого волна 6.6 и завелась
// (отсутствие прибора читается как показание прибора). Поэтому до установки
// серия несёт величину, которой измерение дать НЕ МОЖЕТ: интервал времени не
// бывает отрицательным.
const ConsumerStartDelayUnset = -1

func init() {
	ConsumerStartDelay.Set(ConsumerStartDelayUnset)
}
